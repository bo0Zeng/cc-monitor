    // 性质：`skip_serializing_if` ⇒ 字段在 JSON 里可缺席 ⇒ TS 侧必须是 optional。
    // 少了它，`ts-rs` 的 `maybe_omitted && has_default` 兜底会产出 `x?: T | null`
