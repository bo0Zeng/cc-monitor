/** 今天纳入生成的 Rust 源文件。C02/C03/C04 往里加时，下方计数自检会红一次提醒。 */
/**
 * 派生 `ts_rs::TS` 的 Rust 源文件——**自动发现，不许手写清单**。
 *
 * ## 为什么改成自动发现（C04d 批 3 的教训，而且是同一个坑踩第二次）
 *
 * 原来这里是一张手写数组。C04d 批 2/批 3 在 **7 个新文件**里加了派生
 * （`account_usage` · `subagent` · `ccm_probe` · `config_surface` · `port_forward` ·
 * `acct_iso_deploy` · `hooks_diag`），**但没同步这张清单** ⇒ 下面两条通用性质
 * （`skip_serializing_if ⇒ ts(optional)` · 大整数 ⇒ `ts(type)`）对它们**完全失效**。
 *
 * 实测证据：变异「把 `ForwardStatus.conn_count: u64` 的 `ts(type)` 删掉」→ **守卫全绿**。
 * 那个字段当初配上 `ts(type)` 只是因为我手工盯了生成物，**不是守卫逼我的**
 * ——与 C04c 的 `duration_ms` **同一个失效模式，我又犯了一次**。
 *
 * 一张需要人每批同步的清单，在 7 个批次里必然漂。**所以不留清单**：
 * 递归全仓找含 `ts_rs::TS` 的 `.rs` 文件，再用等号钉住个数
 * （加派生到一个新文件时红一次，逼人来确认——但**范围本身不会漏**）。
 */
function tsDerivingSources(): string[] {
  const out: string[] = [];
  const walk = (dir: string): void => {
    for (const e of readdirSync(resolve(ROOT, dir), { withFileTypes: true })) {
      const rel = `${dir}/${e.name}`;
      if (e.isDirectory()) walk(rel);
      else if (e.name.endsWith(".rs") && read(rel).includes("ts_rs::TS")) out.push(rel);
    }
  };
  walk("src-tauri/src");
  return out.sort();
}

