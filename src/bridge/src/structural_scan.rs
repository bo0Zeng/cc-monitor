///
/// # 🔴 为什么它是**前置**，不是收尾〔`K-R19` 实测，`KR20D1` 逐字点名〕
///
/// `K-R19` 把 6 处「零定义名字当现状说」订正落盘之后，**尺子读数一动没动**
/// （221/350 → 221/350）—— 因为**订正段里逐字引用了旧名字**：
/// 「这里原先写的是 `X`，全仓零定义」这句话本身，就又是一处 `X` 的注释提及。
/// ⇒ **不带墓碑的闸会永远红**，而一条永远红的闸第一天就得被调松，那是本族最坏的结局。
/// 所以标记必须先定下来，再谈装闸。
///
/// # 三个设计问题的答案（`KR20D1` 点名要答的）
///
/// ## ① 加在哪一级：**行级**
///
/// 标记与那个死名必须在**同一行**。三条理由：
///   · 与 [`LINE_ADDRESS_TOMBSTONE`] 同形 —— 那个形状已经在本仓跑通过一轮；
///   · **窗口按构造有界**。段级标记（「本段以下都是历史」）的窗口开到哪儿说不清，
///     而本仓 `KP4` 实测过：`[\s\S]*?` 那种无界窗口**一刀就被绕过**，
///     「有正则」买不到牙，「窗口有界 + 次数钉死」才买得到；
///   · 名字级（`` `x`〔墓碑〕 ``）读起来更碎，而行级已经够细 ——
///     一行里两个死名要一起赦免时，那两个本来就在讲同一件事。
///
/// ## ② 谁能加：**写那句话的人**，而防它变成「红了就贴标签」的逃生舱靠三道
///
///   · **它只赦免那一行那一处**。人群单位是「处」不是「名字」——
///     同一个死名在别处仍然当现状说的话，那一处照样红；
///   · **贴一个墓碑是一次会被看见的记账**：判据把墓碑处数**钉死在登记表里**，
///     贴了不登记 ⇒ 红，登记了盘上没有 ⇒ 也红（保鲜自检）。
///     ⇒ 它进 diff、可 `grep`，而 `K4` 逐字要求 PM **自己读 diff**；
///   · 存量**不许**靠贴墓碑了事 —— 见 ③。
///
/// ## ③ 存量怎么办：**不贴墓碑，走棘轮 + 登记表**
///
/// 现打人群 59 个名字 / 87 处（`>=2` 个下划线，量于本件基点 `38fa388`），
/// 其中绝大多数在本拍写区之外，贴不了；而「哪儿红就往哪儿贴标签」正是要防的那件事。
/// ⇒ 存量逐条登记进 `every_dead_name_named_in_the_prose_is_declared_dead` 的 `INVENTORY`
/// （`K-R17` 那条行号地址棘轮同形），**新写的一律红**；
/// 墓碑**只用于本轮真的改过的那几处订正段** —— 那才是它被造出来要解的那个问题。
///
/// # 🔴 它买不到什么（写明，别把射程写宽了一格）
///
/// 墓碑只声明「我知道这个名字不在代码里」，**判不了「这句话是不是当现状在说」**。
/// 有人把墓碑贴在一句现在时的话上，本条一声不吭 —— 那要读语义，机器读不了。
/// 这是本族**判不了**的那一半，不假装它覆盖了。
///
/// # 🔴 〔`P14` 2026-09-22 现打订正〕上面 ② 第二条那句话**前半是假的**
///
/// 那一条逐字写着：「**贴一个墓碑是一次会被看见的记账**：判据把墓碑处数**钉死在
/// 登记表里**，贴了不登记 ⇒ 红，登记了盘上没有 ⇒ 也红（保鲜自检）」。
/// **后半成立**（`TOMBSTONED` 那条保鲜自检真的在跑）；**前半不成立。**
///
/// 机制：守那张表的是 [`tests::every_dead_name_named_in_the_prose_is_declared_dead`]，
/// 而它的人群是**死名**、不是**标记**。一处标记只有落在「人群内的某个死名」那一行上
/// 才会被记进账；落在别处的标记，那条判据**一个字也看不见** ——
/// 既不因为没登记而红，也不因为被删掉而红。
///
/// 掉出那个人群的路全是构造性的（见 `is_dead_name_shape` 与 `dead_name_corpus`）：
/// 全大写 / 驼峰 / 少于两个下划线的名字 · 不带反引号的写法 · 那个名字今天还活着 ·
/// 那一行根本没点任何名字（纯叙事的墓碑） · 那份文件不在语料里
/// （`tests/evidence/` · vendored 代码 · 那条判据自己住的那一份）。
///
/// ## 死值验读数（2026-09-22，本件基点）
///
/// 刀口：删掉 `tests/bridge/structural_scan_tests.rs` 里**唯一那一处**带标记的墓碑
/// （它点的是那条已退役的前提闸留下的旧名字；而那份文件按构造被摘出了死名语料
/// ⇒ 那个名字从来没进过人群）。
/// 读数：`cargo test -p monitor --lib` **1753 passed / 0 failed** —— **一格没红**。
/// ⇒ 这比 `P14` 题面说的**更宽一格**：不是「没挂标记的」可以被静默删掉，
///    是「标记没落在人群内死名上的」都可以 —— 而那**包括挂了标记的**。
///
/// 全树读数（`src` ＋ `tests` 两棵互不包含的根，`grep -o` 不截断）：
/// 标记 **93 处 / 48 份文件**，而 `TOMBSTONED` 登记的是 **82 处死名 / 43 份文件**。
/// 其中 **5 份文件在 `TOMBSTONED` 里一行都没有**（合 **15 处**标记）——
/// 一份文件零登记，就意味着它的标记**没有一处**落在人群内的死名上
/// ⇒ 那 15 处按构造零判据。
/// ⚠ 15 是**下界**：已登记那 43 份里标记与死名不是一一对应（一行可以点两个死名），
/// 逐处的账那张表答不出来。
///
/// ⇒ 补 [`prose_tombstone_marks`] / [`prose_tombstone_near_misses`]：人群改成从
///   **文件系统全集**派生，**一处标记就是一处人群成员**，与它那一行点没点名字无关。
///   判词住 [`tests::every_prose_tombstone_mark_is_registered`]。
pub const PROSE_NAME_TOMBSTONE: &str = "〔散文墓碑〕";

/// [`PROSE_NAME_TOMBSTONE`] 的**内芯** —— 去掉首尾那一对定界符之后剩下的那几个字。
///
/// 为什么非要它：[`prose_tombstone_near_misses`] 要找的是「**想挂标记却没挂上**」
/// 那一形（定界符里多塞了一个日期、或者干脆只写了内芯），而那一形按定义
/// **不含完整标记** ⇒ 针只能从标记本身**运行期拆**出来。
/// 写成第二份字面量的话，本文件与判词文件自己就双双进了那两个人群 ——
/// 而那正是本模块从头到尾在治的「判据在自己的语料里找到自己 ⇒ 恒绿」。
///
/// ⚠ 它**不校验**定界符成不成对（那要另一份字面量）。校验归判词那边的抽取器自检：
/// 内芯必须非空、必须比标记短、必须是标记的子串。
pub fn prose_tombstone_core() -> &'static str {
    let m = PROSE_NAME_TOMBSTONE;
    let mut ci = m.char_indices();
    let head = ci.next().map_or(m.len(), |(_, c)| c.len_utf8());
    let tail = ci.last().map_or(head, |(i, _)| i);
    &m[head..tail.max(head)]
}

/// 数 `text` 里 [`PROSE_NAME_TOMBSTONE`] 的**出现处数**。
///
/// 口径是「处」不是「行」：一行里挂两处标记就算两处 —— 人群单位必须与
/// `TOMBSTONED` 那张表的单位对得上（那张表数的也是处数）。
pub fn prose_tombstone_marks(text: &str) -> usize {
    text.matches(PROSE_NAME_TOMBSTONE).count()
}

/// 枚举 `text` 里**提了这件事却没把标记挂上**的行（1 基行号）。
///
/// # 它是**登记表 ＋ 棘轮**，不是真伪判据
///
/// 人群口径：「这一行出现了 [`prose_tombstone_core`] 而**没有**完整标记」。
/// 它同时收到两类，而机器分不开（要读语义）：
///   ㈠ **真的挂歪了** —— 定界符里多塞了东西（现打有三处是往里塞了一个日期）
///     ⇒ 完整标记比不上 ⇒ 那一处的记账整个落空，而**贴的人以为贴上了**。
///     这是本条最值钱的那一格：它逮的是「以为自己受保护，其实零判据」。
///   ㈡ **在谈这件机制本身** —— 量具脚本里的针、死值验记录里的叙述。合法。
/// ⇒ 出路照本仓的老形状：**存量逐条登记 + 新写的一律红**。
///
/// # 🔴 它买不到什么（`P14` 第一个出口**做不得**的那一半，写死在这里）
///
/// `P14` 的题面给了两个出口：①「删掉一条**没挂标记**的墓碑注释要能红」；
/// ②「明写只有带标记的才受保护，并说清代价」。**① 在一般情形下做不得**，
/// 理由不是省事：
///
/// · 「这段注释是不是一块墓碑」**要读语义**。唯一不读语义的替代是**历史限定词词表**
///   （「原先」「已删」「搬走了」「退役」…），而本仓为这条路栽过两次 ——
///   `K-R6` 网 A 与 `K-R18` R1 都是**开放类**自然语言词表，怎么枚都枚不全 ——
///   并且 `frame_cadence_guard` 那条判据上有一句逐字裁决：试跑那种规则**今天**
///   误红的全是合法文本，「把限定词表调到全绿就是曲线拟合」。
///   ⇒ 由写的人**声明**，不由判据**猜**。这一句是 [`LINE_ADDRESS_TOMBSTONE`]
///   与本标记存在的全部理由，① 等于把它推翻。
/// · 唯一**不读语义**就能认出「这句话点了一个已经不在的东西」的人群，就是
///   [`tests::every_dead_name_named_in_the_prose_is_declared_dead`] 那个死名人群 ——
///   而落在那个人群里的、**没挂标记**的墓碑**今天已经会红**（它进 `INVENTORY`，
///   把那一行删掉 ⇒ 那张表的保鲜自检红）。
///   ⇒ ① 里**机器做得到的那一块早就做完了**，剩下的恰好是「要读语义」的那一块。
///
/// ⇒ 本条走 ②，而**走 ② 之前必须先把 ② 那句话变成真的** ——
///   见 [`PROSE_NAME_TOMBSTONE`] 头注那段订正：今天连「挂了标记的」都没全受保护。
///   补完之后那句话才配写下来，代价也才说得清：
///   **一块既没挂标记、又没点任何人群内死名的墓碑，本仓不判。**
///   它的处置是纪律而不是机检 —— 写墓碑就把标记挂上（挂上就被钉住：删不掉，
///   也贴不了空头），而「挂歪了」这一形由本函数接。
pub fn prose_tombstone_near_misses(text: &str) -> Vec<usize> {
    let core = prose_tombstone_core();
    text.lines()
        .enumerate()
        .filter(|(_, l)| l.contains(core) && !l.contains(PROSE_NAME_TOMBSTONE))
        .map(|(i, _)| i + 1)
        .collect()
}

/// 枚举 `text` 里每一处 `文件.rs:行号`（`文件.rs:行号-行号` 只取头一个数）。
///
/// 带 [`LINE_ADDRESS_TOMBSTONE`] 标记的那一行**不进枚举**（形 B）。
/// `文件.rs::符号` **不会**被误收：`::` 后面不是数字。
pub fn line_addresses(text: &str) -> Vec<LineAddress> {
    let mut out = Vec::new();
    for (i, line) in text.lines().enumerate() {
        if line.contains(LINE_ADDRESS_TOMBSTONE) {
            continue;
        }
        let b = line.as_bytes();
        let mut from = 0usize;
        while let Some(k) = line[from..].find(".rs:") {
            let at = from + k;
            let mut e = at + 4;
            let mut n = 0usize;
            let mut any = false;
            while e < b.len() && (b[e] as char).is_ascii_digit() {
                n = n * 10 + (b[e] - b'0') as usize;
                any = true;
                e += 1;
            }
            if any {
                let p = path_before(line, at);
                if !p.is_empty() {
                    out.push((i + 1, format!("{p}.rs"), n));
                }
            }
            from = at + 4;
        }
    }
    out
}

