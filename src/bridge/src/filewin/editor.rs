//! 第一版只想到 ①，顺手对「每行 8 KiB」那一档断言了 `!buys_nothing()`
//! —— **当场红**，因为 256 KiB / 8 KiB 只有 32 行，比一屏还少。
//! ⇒ 散文里原本就漏了一种，而它不是靠复读散文补上的。
//! （住 [`tests::windowing_buys_nothing_on_a_file_that_is_one_long_line`]。）
//!
//! ⚠ **还有一条更重的路被量过之后放掉了**：也可以**完全不用 `TextEdit`** ——
//! 自己按 [`super::rows`] 那条路用 `ScrollArea::show_rows` 逐行画 galley、
//! 自己做光标/选区/输入法。它更彻底，但它要从零做的正是上表里 ✅ 的那几格
//! （光标渲染 · 选区 · 输入法），而窗口化 `TextEdit` 把这些在**窗口内**白拿。
//! ⇒ 两条里**窗口化 `TextEdit` 便宜得多**，所以上表按它写。
//!
//! ───────────────────────────────────────────────────────────────────────
//! ## §四.3 三问：**上限该定多少、还要不要有上限**
//! ───────────────────────────────────────────────────────────────────────
//!
//! ### (a) 🔴 今天这个上限**守错了维度** —— 而那是一条**现在就在犯**的缺陷
//!
//! 恒 **256 KiB**，只改**行结构**（ASCII，每帧改一个字 = 打字帧）：
//!
//! ⚠ **debug 那两列是两趟（同机、不同负载）的并集，最宽处差近两倍**
//! —— 那本身就是本仓那条「一趟不算读数」的实证。release 那两列是一趟里
//! 连打三帧 × 三档语料。
//!
//! | 段数 | 每段字节 | debug 换行开 | debug 换行关 | **release 换行开** | release 换行关 |
//! |---:|---:|---:|---:|---:|---:|
//! | **1** | 262 144 | 223.7 – 382.3 ms | 212.9 – 407.4 ms | **33.5 – 54.3 ms** | 30.7 – 54.0 ms |
//! | 33 | 8 192 | 1.29 – 3.15 ms | 1.13 – 2.79 ms | **0.11 – 0.25 ms** | 0.08 – 0.15 ms |
//! | 513 | 512 | 1.77 – 3.74 ms | 1.61 – 3.09 ms | **0.19 – 0.29 ms** | 0.17 – 0.26 ms |
//! | 4 097 | 64 | 5.16 – 8.69 ms | 5.12 – 10.92 ms | **0.79 – 1.11 ms** | 0.80 – 1.14 ms |
//!
//! 🔴 ⇒ **同样 256 KiB，最快与最慢差 200 倍以上（release：0.19 ms vs 54.3 ms），
//!    而字节上限一个都分不出来。**
//!    一份 256 KiB **压成一行**的 JSON / 一行日志，**今天就能打开编辑**，
//!    而每敲一个键 release 要 **33.5–54.3 ms**（≈ 18–30 fps，2–3 倍帧预算）。
//! ⇒ 所以「超预算」这件事**今天就在发生**，只是它的自变量不是字节数，是
//!   **最长的那一行有多少字节**。
//! ⚠ 反过来：一份 **1 MiB** 的规整配置（每行 64 字节）打字帧 release
//!   3.17–4.45 ms —— **比那份 256 KiB 一行的快十倍**，却被今天的上限**拒掉**。
//!
//! ### (b) 开窗之后瓶颈换成什么 —— **量出来的是三笔，都在排版之外**
//!
//! 先看排版这一维（每行 64 字节，每帧改一个字）：
//!
//! | 全文 | 行数 | debug 整份 | debug 只排 40 行 | **release 整份** | **release 只排 40 行** |
//! |---:|---:|---:|---:|---:|---:|
//! | 256 KiB | 4 096 | 7.2 – 9.4 ms | 0.31 – 1.45 ms | **0.79 – 1.15 ms** | **0.02 – 0.06 ms** |
//! | 1 MiB | 16 384 | 27.5 – 42.1 ms | 0.40 – 1.29 ms | **3.17 – 4.45 ms** | **0.02 – 0.06 ms** |
//! | 4 MiB | 65 536 | 80.4 – 147.3 ms | 0.30 – 1.26 ms | **12.60 – 18.45 ms**（🔴 跨预算线） | **0.02 – 0.07 ms** |
//! | 16 MiB | 262 144 | 321.2 – 450.1 ms | 0.30 – 0.95 ms | **53.0 – 75.5 ms** | **0.02 – 0.06 ms** |
//!
//! ⇒ 右边那一列在 **64 倍**字节跨度上**恒定**（release 0.02–0.07 ms）。
//!   这正是 [`super::rows`] 那条判据的**相等**形状，而不是「变少」形状
//!   —— 所以它由 [`tests::the_bytes_handed_to_layout_are_equal_no_matter_how_big_the_file`]
//!   钉成一条**相等**断言，并且同一条判据里放了**故意不开窗**的对照组。
//!
//! 🔴 **下一堵墙在这三笔，而它们都不是排版：**
//!
//! | 全文 | egui 自己每帧的全量克隆（**2×**，聚焦时） | [`Pane::dirty`] 全量比 | `String` 中间插一字 | `decode_editable`（NUL 扫 ＋ UTF-8 验 ＋ 一次全量拷） |
//! |---:|---:|---:|---:|---:|
//! | 256 KiB | 0.01 – 0.03 ms | 0.00 – 0.04 ms | 0.00 – 0.01 ms | 0.02 – 0.05 ms |
//! | 4 MiB | 0.21 – 1.93 ms | 0.06 – 0.19 ms | 0.04 – 0.05 ms | 0.38 – 0.97 ms |
//! | 16 MiB | 1.47 – 6.68 ms | 0.53 – 0.71 ms | 3.38 – 3.50 ms | 4.46 – 4.96 ms |
//! | **64 MiB** | **25.1 – 36.9 ms** | 2.82 – 3.68 ms | 1.16 – 1.32 ms | **17.60 – 19.42 ms** |
//!
//! （以上 release 档。）那两次全量克隆是 **egui 自己干的，不是我们的代码**：
//! `builder.rs` 与 `:1375` 各一行 `text.as_str().to_owned()`，
//! 于是**聚焦的 `TextEdit` 每帧要把整份文本堆拷两遍**（还有 `builder.rs`
//! 那一行 `prev_text`，**不分聚焦与否，每帧一次** ⇒ 一共三次）。
//! ⇒ 64 MiB 上单这一笔就是 **1.5 倍帧预算**，而它**换不掉的 layouter 钩子管不到**。
//!
//! 🔴 **而开窗顺带把这一笔也治了** —— 控件手上只有窗口 ⇒ 它每帧克隆的也只是窗口。
//! **这是「只排视口内」除排版之外的第二个收益，也是本节唯一一条
//! 「用户以为的代价里没有、而它其实白拿」的东西。**
//!
//! 🔴 **内存那一维是本节唯一一处两个来源打架、而我没有把它拉平的**，如实登记：
//! - **现打（下界）**：262 144 字节排一帧、galley 还活着时，进程常驻内存
//!   净增 **debug 1 MiB / release 0 MiB**；1 048 576 字节那一档**两档都是 3 MiB**。
//!   ⇒ 大致**与文本同量级到三倍**，而不是几十倍。
//!   ⚠ 它是**下界**：分配器不把释放的页还给内核，同进程里先前的峰值会让
//!   后面的分配「白拿」已有的页。而且这把尺子**错了两次才跑对**
//!   （读数取在 `Context` 被丢之后 ⇒ 恒 0；换 `VmHWM` 峰值 ⇒ 也恒 0，
//!   因为峰值是进程级的）—— 逐条记在那条判据里。
//! - **按结构算（不是量）**：`Glyph` ＋ 每字符四个顶点的网格 ≈ 172 字节/字符
//!   ⇒ 262 144 字节 ASCII 约 **45 MB**。
//! - 🔴 **两者差 45 倍，本刀没有把它拉平** ⇒ 「内存上限该多少」这一问
//!   **今天答不了**，而这正是 §四.3(c) 不动 `MAX_EDIT_BYTES` 的第一条理由。
//!   要答它得上真的分配器计数（`dhat` / `jemalloc` 统计），本刀没做。
//! ⚠ 而 egui 的撤销栈默认 `max_undos = 100`（`util/undoer.rs`）、快照是全文
//! ⇒ **算出来**（不是量出来）的撤销栈上界 = 100 × 全文：
//! 256 KiB ⇒ 25 MiB；4 MiB ⇒ 400 MiB；64 MiB ⇒ 6.4 GiB。
//! ⇒ 开窗之后这两项也都从「全文」降成「窗口」。
//!
//! ### (c) 🔴 **所以这个上限该怎么办** —— 三条，都带读数
//!
//! 1. **字节上限不该是唯一的闸**：它在 300 倍的真实代价差上**完全盲**（(a)）。
//! 2. **该加的第二个量是「最长的一行有多少字节」**，理由两条指向同一个量：
//!    ① epaint 只能按 `\n` 切段，**一段就是它不可再分的排版单位**（§四.1c）；
//!    ② 视口那扇窗**必须装得下整行**（§四.2 第 10 条）。
//!    ⇒ 这不是巧合，是同一个约束的两面。它由 [`LineIndex::longest_line`] 给出。
//! 3. 🔴 **本刀不动 `MAX_EDIT_BYTES` 那个数**，两条理由都是硬的：
//!    - **读数还不支持任何一个具体的新数**：release 上 4 MiB 的规整文本打字帧
//!      两趟量到 **12.60–18.45 ms**，**横跨 16.67 ms 那条线** ——
//!      连「4 MiB 行不行」都答不死；而内存那一问（下面）本节也没答完。
//!      ⇒ 定一个新数要与那一问同拍答，否则又是「拿没有形状的东西定数」
//!      （第一节踩过的同一个坑）。
//!    - 🔴 **写区之外有人恒等钉着它**：`tests/bridge/byte_cap_registry_tests.rs`
//!      按源码文本把这一项钉在 `256 * 1024`，而那个文件**不在本刀写区**
//!      ⇒ 改那个数就是留一条**本刀修不了的红**。
//!      ⇒ 改这个数必须与 `byte_cap_registry` 同拍，归下一刀。
//!
//! ───────────────────────────────────────────────────────────────────────
//! ## §四.4 四问：**有没有更便宜的等价物**（硬要求：先量，再下判）
//! ───────────────────────────────────────────────────────────────────────
//!
//! ### (α) 「把软换行关掉」—— 🔴 **量了，而量出来的是「这把尺子分不开」**
//!
//! §四.3(a) 那张表里「关」与「开」并排：**两者的差比同一档跑两趟的差还小**，
//! 而且方向不固定（4 097 段那一档「关」现打还**更慢**）。
//! ⇒ **关软换行买不到可测的加速。**
//!
//! ⚠ **而这一档的实验不是单变量的，如实登记**：multiline 上关不掉软换行
//! （§四.1a），只能自己递一个 layouter 进去；而那个手写的 layouter 与
//! `.code_editor()` 那一支**不止差一个换行** —— 字号是手写死的、
//! 每段的 `line_height` 没设。⇒ 严格说那两列比的是**两种 layouter**，
//! 不是「同一个 layouter 开不开换行」。
//! ⇒ 所以结论只到这里：**关换行没有量到加速**，而**不是**「加速确切为零」。
//! 要把它量干净得动 epaint 那一侧，本刀没做。
//!
//! ⚠ **这条读数照样改变了结论，正是硬要求量它的理由**：不量的话很容易把
//!   「关软换行」当成一个便宜的优化先上；实际上它是**只排视口内的几何前提**
//!   （§四.2 第 5 条），单独上只换来「长行不再折」这个**可见的退步**。
//! ⚠ 它另有一个**没量到**的副作用值得记：`wrap.max_width` 设成 `f32::INFINITY`
//!   之后 `epaint-0.36.2/src/text/fonts.rs` 那段取整分支不走了 ⇒ **缓存键与控件宽度无关**
//!   ⇒ 改窗口大小不再让整份 galley 失效。本机**没量**（要真窗口改大小）。
//!
//! ### (β) 「什么都不做，靠 galley 缓存」—— 在**今天的上限内**其实够用
//!
//! 手停着一帧 0.98–1.27 ms（debug）；满上限、行结构正常时打字帧 release
//! **0.79–1.15 ms**，余量 14 倍以上。
//! ⇒ **在「多行 ＋ 不超今天上限」这一族文件上，今天没有性能问题。**
//! 🔴 但它对 (a) 那一族（一行 256 KiB，release 33.5–54.3 ms）**完全无效**：
//!    缓存命中不了（文本每帧都变），切段也切不出来（只有一段）。
//!
//! ### (γ) 「靠上游的按段缓存」—— **已经在用了**，且已计入所有读数
//!
//! §四.1c：`allow_split_paragraphs = true` 是上游默认，生产那条路已经吃到了。
//! ⇒ 它不是一个候选项，是基线。
//!
//! ### (δ) 「对最长一行超标的文件出声 / 拒编」—— **最便宜，而且治的是唯一真在犯的那一档**
//!
//! 不需要开窗、不需要动控件、不需要自己的撤销栈，
//! 而它治的正是 (a) 那族 release 33.5–54.3 ms。
//! ⚠ 但它是一次**行为变更**（今天能开的文件明天开不了 / 多一句警告）
//! ⇒ **本刀不擅自上**，它是一个要用户拍板的裁决，摆在报告里。
//!
//! ───────────────────────────────────────────────────────────────────────
//! ## 🔴 §四.5 裁决：**这条路做得动，但读数说它不该是下一步**
//! ───────────────────────────────────────────────────────────────────────
//!
//! - **做得动**：机制在 egui 0.36.2 上齐备（窗口化 `TextEdit` ＋
//!   `ScrollArea::show_rows`），收益也现打量到了，而且是**相等**形状的收益
//!   （release 0.02–0.07 ms **恒定** vs 0.79→75.5 ms **线性**）。
//! - 🔴 **但它在今天的上限上买到的是约 1 ms／键，在一个 16.67 ms 的预算上**
//!   —— 6 % 的一帧。用户裁这条路时手上那个依据（「16.3 ms 几乎吃掉整帧」）
//!   是一个 **debug ＋ 冷首帧**的数（§四.0）。
//! - 🔴 **而它治不了唯一真在超预算的那一族**（一行特别长：release 33.5–54.3 ms／键）
//!   —— 因为一扇窗必须装下整行（§四.2 第 10 条，由 [`WindowingPayoff::buys_nothing`]
//!   钉成相等断言）。现打：那一族**开窗与整份同值**
//!   （release 38.99–53.86 vs 37.75–52.64 ms）。
//! - **代价的大头也不在排版**：在**把光标 / 选区 / 撤销栈重做在全文坐标上**
//!   （§四.2 第 1 / 2 / 3 条），其中第 3 条**不做就会静默改坏用户的文件**
//!   ⇒ 那一格没有「先凑一个能用的」这个选项。
//!
//! ⇒ **本刀的排法**：把上面这些量出来、写下来、**把能钉成判据的钉成判据**
//! （[`LineIndex`] / [`Window`] / [`WindowingPayoff`] 那一组 ＋ 它们的相等断言），
//! 而**不把它接进生产**。
//! 🔴 **如实登记「没做」的那一半**：生产那个 `TextEdit` 在
//! `filewin/shell.rs` 里 `editing_text_mut()` 那一处 `TextEdit::multiline`，**不在本刀写区**（另一路正在改那棵树的结构）
//! ⇒ 本节这组东西**一个生产调用方都没有**。
//! 按本仓那条「**判据不在执行链上就等于不存在**」：
//! **「只排视口内」这个功能今天没有落地，也不许读成落地了。**
