//! # 🔴 一、进程形态：**同进程**（Tauri webview 主窗 ＋ egui 原生窗）
//! ═══════════════════════════════════════════════════════════════════════
//!
//! ## 结论
//!
//! **egui 的窗口与 Tauri 的 webview 主窗跑在同一个进程里**，egui 那条事件循环
//! 住**次线程**，Tauri／`tao` 照旧占主线程。**不需要独立二进制，也就不需要新开一条 IPC。**
//!
//! ## 问题是真的：两个事件循环，一个主线程
//!
//! Tauri 2.11 在 Linux 上经 `tao 0.35.2` 落到 **GTK3**（`gtk 0.18` ＋ `webkit2gtk`），
//! 它的事件循环在主线程上。`eframe` 走 `winit 0.30.13`，winit 默认**也要主线程** ——
//! winit 的 `platform_impl::linux::EventLoop::new` 里那道检查逐字：
//!
//! ```text
//! if !attributes.any_thread && !is_main_thread() { panic!(...) }
//! ```
//!
//! ## 但它有现成解法，而且是两边都提供的一等 API（**现打核过源码，不是查记忆**）
//!
//! | 现物 | 住址 | 是什么 |
//! |---|---|---|
//! | `with_any_thread` | `winit-0.30.13/src/platform/{x11,wayland,windows}.rs` | 把上面那道主线程检查关掉；**x11 / wayland / windows 三个平台都有** |
//! | 关掉之后走哪条路 | winit `platform_impl::linux::EventLoop` | 分派到它自己那两个「任意线程」构造器（x11 一个 / wayland 一个） |
//! | 用户代码怎么够得着 | `eframe::NativeOptions::event_loop_builder` | 一个 `EventLoopBuilderHook` |
//! | 它真的被调用 | `eframe::native::run::create_event_loop` | `builder.build()` **之前**执行这个 hook |
//!
//! ⇒ 不用 fork eframe，也不用自己接 winit：设一个 hook 就够。见 [`shell`]。
//!
//! ⚠ macOS **没有**这个扩展 trait（NSApplication 铁定要主线程）。
//!   本仓承诺的平台是 **Windows / Linux**（`Cargo.toml` 的 `description` 逐字），
//!   ⇒ 这条限制今天碰不到；**哪天要上 macOS，这个结论必须重判。**
//!
//! ## 现打：不是只看了源码，真跑起来量过
//!
//! 原型住 scratchpad（**刻意不进仓** —— 它要 `tao` 与 `eframe` 两条依赖，
//! 而 `tao` 不是本 crate 的直接依赖）。跑法：`Xvfb` ＋ 软渲染。
//!
//! | 趟 | 读数 |
//! |---|---|
//! | ① tao 主线程建窗 ＋ eframe 次线程建窗（wgpu／lavapipe） | `egui_frames=31` · `egui_error=None` · **退出码 0** |
//! | ② 同上，加看门狗连跑 29 秒 | egui 次线程 **17 945 帧 / 29 秒**（约 600 fps），全程不崩、不死锁 |
//! | ③ 🔴 **对照组**：`PROBE_NO_EGUI=1`，同一个二进制、不起 egui 线程 | tao 的用户事件计数**照样是 0** |
//! | ④ 换成**仓里真用的那个后端**（`glow`／软 GL）重打一遍 | egui 次线程 **31 072 帧 / 20 秒**，同样不崩、不死锁 |
//!
//! ⚠ 第 ④ 趟是必须的，不是锦上添花：①②③ 量的是 `wgpu` 后端，而仓里最后定的是 `glow`
//! （理由住 `Cargo.toml` 那条依赖的头注 —— `wgpu` 在本仓交叉编译到 Windows 时编不过）。
//! **换了被测对象就要重打读数**，否则这一节说的是另一个配置的事。
//!
//! 🔴 **第 ③ 趟是这组读数里最要紧的一条。** 第 ② 趟里 `tao_user_events=0`，
//! 看起来像「egui 把 tao 饿死了」。**对照组把这条错误结论挡掉了**：
//! 把 egui 整条线程摘掉，那个计数**仍然是 0** ⇒ 0 是我那根探针（tao 的
//! `EventLoopProxy` 在 GTK 上的唤醒）自己的毛病，**与共存无关**。
//! 没有这个对照组，这里会写下一条「两个循环打架」的假读数。
//!
//! ## ⚠ 这组读数**买不到**什么（逐条写明，别读宽）
//!
//! - **没有真图形会话**：本机 `XDG_SESSION_TYPE=tty`（同 `真相源/99 §一`）。
//!   上面是 `Xvfb` ＋ 软渲染 lavapipe 的读数，**不是真合成器上的**。
//! - **主线程那侧是裸 `tao` 窗口，不是真的 Tauri app**（没有 webkit2gtk webview 在跑）。
//!   「再塞一个 WebView 进来还成不成立」**没量**。
//! - **Windows 上一次都没跑过**（手上没有 Windows 机器）。那侧今天只有两条：
//!   winit 的 `EventLoopBuilderExtWindows` 有 `with_any_thread`，以及 `winchk` 那一格的交叉编译过得了。
//!
//! ## 为什么不走「独立二进制 ＋ 一条 IPC」那条退路
//!
//! 退路本身是通的，但它有一条**不是工作量的**代价：
//! `sftp_pool.rs::pool` 那个连接池是一个**进程级 `OnceLock`** ——
//!
//! ```text
//! fn pool() -> &'static Mutex<HashMap<String, Arc<OriginPool>>>
//! ```
//!
//! ⇒ 换进程就是换一份池：同一台远端会被**拨第二条 SSH 连接**，
//! 而 `设计/60 §5.4a` 那套「一条连接 ＋ 6 通道闸 ＋ 4 传输车道闸，`6 − 4 = 2`
//! 格永远留给浏览」会**悄悄变成两份互不知情的预算** —— 而那个差**已经被秤 F4 钉成相等读数**。
//! ⇒ 独立二进制不是「多一跳 IPC」，是**把一条已经有判据的不变量拆成两份**。
//!
//! ═══════════════════════════════════════════════════════════════════════
//! # 二、住址：`src/bridge/src/filewin/` —— `monitor` 自己的一个模块
//! ═══════════════════════════════════════════════════════════════════════
//!
//! 两条独立的理由指向同一个地方：
//!
//! 1. **同进程**（上面那一节）⇒ 代码必须链进 app 那个二进制 ⇒ 它得是
//!    `monitor` 或 `monitor` 的依赖。
//! 2. **门禁 `cargo` 那一格把 workspace 包数恒等钉在 9**
//!    （`gate.sh` 里逐字写着 `run_gate_sum cargo 9`；
//!    判法住 `gate.sh` 的 `run_gate_sum`，包数不等就红）。
//!    新增任何一个 workspace 成员（哪怕叫 `crates/filewin-core`）都会让那一格当场红，
//!    而那个 `9` 住 `gate.sh` —— **不在 24e 的写区** ⇒ 不许为了塞一个 crate 去改判据。
//!
//! ⇒ 落成模块，包数不动；判据走 `monitor` 的 `cargo test --lib`，
//!   **正好就在门禁 `cargo` 那一格的执行链上**。
//!
//! ⚠ **旧面板 `src/sftp/panel.ts`（716 行）这一刀不删。**
//!   `设计/60 §6.6` C 件裁的「只有一个文件管理面板」是**终局**，
//!   但在这个窗口真能替代它之前删掉旧的，等于把功能拿走。退役放到它真能替代的那一刀。

//! ═══════════════════════════════════════════════════════════════════════
//! # 〔第二刀 2026-09-20〕入口 · 远端那条链 · `§5.4d`
//! ═══════════════════════════════════════════════════════════════════════
//!
//! 第一刀只有「窗口立得起来」；第二刀补三件，逐件的住址与边界写在各自模块头注里：
//!
//! | 件 | 住址 | 它买到什么 / 买不到什么 |
//! |---|---|---|
//! | **① 用户点得开** | [`entry`] | 一条 `#[tauri::command]`，**先列一趟目录再开窗**（列不出来就出声，不静默开一个空窗）。⚠ 买不到「窗口真的出现在屏幕上」—— 本机无图形会话 |
//! | **② 远端那条链** | [`source::parent_dir`] ＋ [`shell::FileWindow::navigate_to`] | 「选一台远端 → 列它的目录 → 双击进下一级 → ⬆ 退回上一级」。⚠ 买不到端到端读数（红线不许起真连接）；买得到的是**行为**（本机那一侧真跑）与**委派**（远端只有一条路，且它调共用池） |
//! | **③ `§5.4d`** | [`transfer`] | **先把覆盖确认一次问完，再并行起传输**。⚠ 买不到真传输；买得到的是那三段的**顺序**与**并行度**（含一条阴性对照：把闸调窄必须真的挡住） |
//!
//! ## 🔴 这一刀**没**处置的两条欠账（第一刀留下的，如实记）
