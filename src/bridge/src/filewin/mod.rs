//!    ② 那块面板自己的退役工序（顶栏那颗按钮改指向、886 行删除、`src/main.ts` 那侧入口）。
//!    两件都不在本刀写区。
//!    🔴 **而现打比那一节写的更强**：那一节数的是「窗口缺的那 8 条里老面板有 6 条」，
//!    **没数到**「窗口的**起点路径**也是老面板给的」—— 入口那条命令吃的是一条
//!    绝对路径，而现打那条路径的唯一来源是老面板那处 `sftp_realpath(cfg, ".")`。
//!    ⇒ 窗口今天连「自己开在远端 home」都做不到。
