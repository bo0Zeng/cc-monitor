//! # 〔第三刀 2026-09-20〕零流量复制接到窗口上（`设计/60 §5` 第三段第 7 步的前半）
//! ═══════════════════════════════════════════════════════════════════════
//!
//! `设计/60 §5` **第二段**（零流量复制）在步 23b 就落地了，住 `sftp_pool::copy_remote_path`，
//! 秤 F3 两个方向钉着它。**但窗口上没有它** —— 第三刀补的就是这一格。
//!
//! | 件 | 住址 | 它买到什么 / 买不到什么 |
//! |---|---|---|
//! | **发起** | [`rows::show_file_rows`] 行上那颗「复制」＋ [`shell::FileWindow::begin_copy`] | 点得到（合成事件下认得出是哪一行）。⚠ 买不到「真机上鼠标点得到」 |
//! | **三段顺序** | [`copy::run_copy`] | 探测 → **一次**问覆盖（`FnOnce`）→ 才动手。照 [`transfer::run_drop`] 的形状办 |
//! | **委派** | [`copy::copy_remote`] | 调的是 `sftp_pool::sftp_copy`（围栏 ＋ 取消登记 ＋ 车道预算全在它里面）。⚠ 买不到一趟真复制的读数 |
//! | **退路出声** | [`copy::outcome_notice`] ＋ [`copy::CopyBoard::ui`] | 退了路那句话（含过网字节数）**真的被画出来了**（判据从 egui 这一帧的 galley 里读回来）。⚠ 买不到「那几个像素没被列宽切掉」 |
//!
//! 🔴 **这一格逼出了一条真缺陷，值得单独记**：
//! 「整行可点」那块命中矩形横向拉满整行宽 ⇒ 它**把行上那颗按钮整个盖住**。
//! egui 的命中测试在平手时逐字「In case of a tie, take the last one = the one on top」
//! （那句话住 `egui-0.36.2/src/hit_test.rs` 挑「最近那个可点控件」的私有辅助函数里），
//! 而那块整行矩形是**后**登记的
//! ⇒ 按钮编得过、画得出、**永远点不到**。⇒ 整行那块矩形现在**让开按钮那一段**，
//! 判据两侧都钉（点按钮要回按钮、点空白处双击要回那一行）。
//! 这与 `真相源/99 §9.1` 同族：**「调了那个看起来对的 egui API」只证明盘上有。**

