//! 2. **「状态随已访问行数增长」那个盲区**（`scale_tests` 头注）：
//!    `egui_itself_does_not_keep_per_row_state` 钉「状态随列表长度增长」，
//!    钉不住「滚久了会不会越来越胖」。⇒ **这一刀补上了**，见
