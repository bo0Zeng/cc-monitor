//! # 〔第四刀 2026-09-21〕搜索接到窗口上（`设计/60 §3.5`）
//! ═══════════════════════════════════════════════════════════════════════
//!
//! `设计/60 §3.5` 是「唯一必须走后端的那一件」。后端那半在 `24f` 的三刀里做完了
