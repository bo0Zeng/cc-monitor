//!
//! [`rows::show_hit_rows`] 的「命中行一个可点控件都不画」在第四刀是**一条纪律**
//! （两条路共用 `RenderTally`）。第五刀行上多了三颗**写**按钮 ⇒ 那个坑的代价
//! 从「复制到错的地方」升级成「**删错东西**」。⇒ 命中那一摞的收数口换成了
//! [`rows::HitTally`]（连一个「谁被点了」的字段都没有）⇒ 从此**由编译器守**。
//!
//! ## 🔴 这一刀**没**处置的（逐条，别读宽）
//!
//! 1. ✅ **`sftp_download`（往外拖）** —— 〔第八刀 09-21〕做了，住 [`download`]。
//!    ⚠ 那时这一条写的是「另一个交互题（选本机目标目录）」，而**那个交互题的答案
//!    不是原生对话框** —— 它能不能从 egui 那条线程弹出来在本机量不到
//!    （无图形会话）⇒ 走了窗口自己那套「问一句」。逐条理由住 `download.rs` 头注。
//!    🔴 顺带修掉一个**本机侧的洞**：`sftp_download` 的落点从来没过那道 Claude
//!    数据围栏（三张账首尾相接推诿、链子末端一句假话）⇒ 围栏补在池子那一层，
//!    老面板与窗口两条路一起修。
//! 2. ✅ **`sftp_read_text_for_edit` / `sftp_write_text`（文本编辑）** ——
//!    〔第九刀 09-22〕做了，住 [`editor`]。`设计/60 §5.4b` 指名留给 `24e` 的两问
//!    都答了：「超了怎么办」＝ 窗口按 `size` 在**本地**判，连往返都不发，
//!    把三件事分成两句人话（零签名改动）；「这个量该多大」＝ **保持 256 KiB**，
//!    而这一次它有现打依据（满上限排一帧 **16.3 ms**，而 60 fps 预算 16.67 ms
