//! # 🚫 一、进程形态：**本节原先写「同进程」，那句话 2026-09-23 作废**
//!
//! 上一版这一整节（含「两个事件循环一个主线程」的现打、`with_any_thread` 那条一等 API、
//! 以及「为什么不走独立二进制 ＋ 一条 IPC」那条退路的理由）逐字结论是**同进程**。
//! **它今天不成立** —— 用户 2026-09-22 裁「窗口生命周期就是销毁」，而
//! **winit 一个进程只许一个事件循环** ⇒ 同进程里第二次开窗必然失败
//! ⇒「关掉就销毁」＋「还能再打开」在同进程形态下**不可同时成立**。
//!
//! **今天的形态与它的代价**住两处：形状与「买到/买不到」在 [`proc`] 的头注，
//! 设计与被推翻的那三句住 `设计/60 §4.8` 的作废块。**这儿不留第二份**（`D2`）。
//!
//! ⚠ 那一节里有一样东西**没有随它作废**：它记的那组「真跑起来量过」的读数
//! （两个事件循环在同一进程里能不能共存）**仍然是真的** —— 变的不是那个事实，
//! 是它还管不管这道题。原文在 git 历史里。
//! # 二、住址：`src/bridge/src/filewin/` —— `monitor` 自己的一个模块
//! ═══════════════════════════════════════════════════════════════════════
//!
//! 两条独立的理由指向同一个地方：
//!
//! 1. **同进程**（上面那一节）⇒ 代码必须链进 app 那个二进制 ⇒ 它得是
//!    `monitor` 或 `monitor` 的依赖。
//! 2. **门禁 `cargo` 那一格把 workspace 包数恒等钉在 9**
//!    （`gate.sh` 里逐字写着 `run_gate_sum cargo 10`；
//!    判法住 `gate.sh` 的 `run_gate_sum`，包数不等就红）。
//!    新增任何一个 workspace 成员（哪怕叫 `crates/filewin-core`）都会让那一格当场红，
//!    而那个 `9` 住 `gate.sh` —— **不在 24e 的写区** ⇒ 不许为了塞一个 crate 去改判据。
//!
//! ⇒ 落成模块，包数不动；判据走 `monitor` 的 `cargo test --lib`，
//!   **正好就在门禁 `cargo` 那一格的执行链上**。
//!
//! ⚠ **旧面板 `src/sftp/panel.ts`（716 行）这一刀不删。**
//!   `设计/60 §6.6` C 件裁的「只有一个文件管理面板」是**终局**，
//!   但在这个窗口真能替代它之前删掉旧的，等于把功能拿走。退役放到它真能替代的那一刀。

