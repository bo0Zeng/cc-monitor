//!
//! ## 🔴 这一刀**没**处置的（逐条，别读宽）
//!
//! 1. ✅ **`sftp_download`（往外拖）** —— 〔第八刀 09-21〕做了，住 [`download`]。
//!    ⚠ 那时这一条写的是「另一个交互题（选本机目标目录）」，而**那个交互题的答案
//!    不是原生对话框** —— 它能不能从 egui 那条线程弹出来在本机量不到
//!    （无图形会话）⇒ 走了窗口自己那套「问一句」。逐条理由住 `download.rs` 头注。
//!    🔴 顺带修掉一个**本机侧的洞**：`sftp_download` 的落点从来没过那道 Claude
//!    数据围栏（三张账首尾相接推诿、链子末端一句假话）⇒ 围栏补在池子那一层，
//!    老面板与窗口两条路一起修。〔FN1 · V119：那道落点围栏今天又拿掉了 —— 用户裁「不需要任何围栏」〕
//! 2. ✅ **`sftp_read_text_for_edit`〔散文墓碑〕 / `sftp_write_text`（文本编辑）** ——
//!    〔第九刀 09-22〕做了，住 [`editor`]。`设计/60 §5.4b` 指名留给 `24e` 的两问
//!    都答了：「超了怎么办」＝ 窗口按 `size` 在**本地**判，连往返都不发，
//!    把三件事分成两句人话（零签名改动）；「这个量该多大」＝ **保持 256 KiB**，
//!    而这一次它有现打依据（满上限排一帧 **16.3 ms**，而 60 fps 预算 16.67 ms
//!    ⇒ 它是天花板不是中值）。
//!    ⚠ **大文件编辑改流式仍然没做** —— 形状没定，而现打说改大直接超帧预算。
//! 3. **多选没做**（`设计/99 §4.7.3 β1` 把它排在本节之后）⇒ 生产那一侧
//!    递进 [`writeops::run_writes`] 的恒是 `N = 1`。「N 个只问一次」那条性质
//!    由它自己的判据按 `N > 1` 喂。
//! 4. **目录递归删除没做**（`sftp_delete` 的 `is_dir` 走 `remove_dir`，只删空目录）。
//! 5. **老面板 `src/sftp/panel.ts` 这一刀照旧不删** —— `设计/99 §4.6.5` 逐字裁定
//!    `P3`（退役）必须排在本节之后，而本刀只接了那五条：`sftp_download` 与
//!    文本编辑那两摊仍然在老面板手上。
//!    ✅〔第八 · 九刀补记 09-22〕**那三条剩件全接完了** ⇒ 池子 13 条命令
//!    窗口全接上（`remote_write_registry_tests` 那条相等断言现打 13 / 缺 0）。
//!    ⇒ `P3`（老面板退役）的**命令前置**全部解开：老面板真喊 12 条
//!    （现打：`sftp_chmod` 与 `copy_remote_path` 它一处都不喊），窗口 13 条
//!    ⇒ **命令层面是超集**。
//!
//!    🔴 **但「命令超集」≠「功能超集」，而这里真差一格**（现打，不是推测）：
//!    老面板 `open()` 有**三种**入口模式，窗口只覆盖两种 ——
//!    | 老面板 | 干什么 | 窗口 |
//!    |---|---|---|
//!    | `initialDir`（F78） | 直接进那个远端目录 | ✅ 入口命令吃的就是一条路径 |
