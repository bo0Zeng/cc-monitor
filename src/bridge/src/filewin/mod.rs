//! # 〔第五刀 2026-09-21〕五条文件操作接到窗口上（`设计/99 §4.6.4` 的前半）
//! ═══════════════════════════════════════════════════════════════════════
//!
//! 用户原话逐字：「**我能连 ssh 对机器文件进行什么操作，后端就应该能进行什么操作，
//! 这才是我想要的远端文件管理器**」。这一刀接的是 `sftp_mkdir` · `sftp_delete` ·
//! `sftp_rename` · `sftp_chmod` · `sftp_cancel_transfer`〔散文墓碑〕。
//!
//! | 件 | 住址 | 它买到什么 / 买不到什么 |
//! |---|---|---|
//! | **发起** | [`rows`] 行上那三颗（改名 · 删除 · 权限）＋ 工具栏那颗「新建目录」 | 点得到（合成事件下认得出是哪一行、哪一颗）。⚠ 买不到「真机上鼠标点得到」 |
//! | **两段顺序** | [`writeops::run_writes`] | **一次**问完（`FnOnce`）→ 才动手。照 [`transfer::run_drop`] 的形状办（〔FN1 · V119〕排在最前面的「围栏」那一段删了） |
//! | ~~围栏~~ | 〔FN1 · V119〕删：本地预判（`writeops::fenced_path`）与池子那四条命令各自的 `guard_write` 都不在了 | 用户「文件管理器全部都可以改. 不需要任何围栏」；判据翻成「会话文件那一行点删除 ⇒ 问一次 ⇒ 答做 ⇒ 后端真收到 `files-delete`」 |
//! | **取消** | [`transfer::CancelDesk`] ＋ [`transfer::launch_unless_cancelled`] | 那个 `transfer_id` 从「造在适配器栈上」搬到了看板上 ⇒ 窗口**第一次说得出**要取消哪一趟；还没起的那几件**一件都不起**。⚠ 买不到「已经在飞的那一趟在池子里真的停了」（要真连接） |
//!
//! ## 🔴 这一刀顺手修掉的一条结构性的坑
//!
//! [`rows::show_hit_rows`] 的「命中行一个可点控件都不画」在第四刀是**一条纪律**
//! （两条路共用 `RenderTally`）。第五刀行上多了三颗**写**按钮 ⇒ 那个坑的代价
