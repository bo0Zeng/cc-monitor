//! | 件 | 住址 | 它买到什么 / 买不到什么 |
//! |---|---|---|
//! | **命令面** | [`find`] | 四条线上命令（`files-find` / `files-index-status` / `files-index-rebuild` / `files-browse`）在客户端侧的第一个发送端。照 `backend_route` 那个共用分流器办，**没另造一套**。⚠ 判据喂的是一台合成后端，**真后端上一趟读数都没有** |
