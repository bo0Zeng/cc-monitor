//!    ⚠ 这一条**我差点写成「超集、可以退役了」** —— 找 `revealPath` 的那趟 grep
//!    没命中它（调用点传的变量叫 `filePath`），是顺着 `openSftpPanel` 的调用点
//!    才翻出来的。⇒ 同 `§4.6.5` 那条方法学：**排退役之前要量「退役那一侧今天在提供什么」**，
//!    而且**不能只按名字 grep**（那正是本仓「截断/错的 grep 不能证明不存在」那一条）。
