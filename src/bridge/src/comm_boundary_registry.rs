//! **通信层的边界登记表**〔`设计/05 §8` 步 1，2026-09-20〕。
//!
//! # 为什么它必须最先
//!
//! `设计/05 §8` 逐字：「**1 必须最先**（否则搬进来的东西没人挡，通信层当天就长业务）」。
//! 而今天这一层**一个文件都还没搬进来** —— 所以本模块的十一条判据从**空集**起步，
//! `§8` 同一行逐字：「判据先对空集成立，随搬迁逐步收紧」。
//!
//! # 🔴 「对空集成立」与「因为空集所以绿」是两件事
//!
//! `设计/05 §3.3.6` 逐字：「**反空真自检：每条判据的绿必须来自一次相等断言，
//! 不许来自"扫不到"**」。它给的那张对照表也是逐字的：
//!
//! | | 错的形状（恒绿）| 对的形状 |
//! |---|---|---|
//! | 人群从哪来 | 「扫某个目录」，扫到几个算几个 | **一张边界登记表** ⇒ 那张表就是人群 |
//! | 断言是什么 | 「人群里没有违例」 | **两条**：① 盘上实际条数 == 登记表条数（相等，不是下界）· ② 人群里没有违例 |
//! | 空集那天 | 绿，而这条绿不携带任何信息 | 绿，但绿的理由是 `0 == 登记的 0` |
//!
//! ⇒ **本模块就是那张表**，以及共用它的十一条判据：
//! `C1`–`C5`（`设计/05 §2` 的铁律）＋ `X1`–`X6`（`§3.3.6` 的签名判据）。
//! `§8` 逐字：`X1–X6` 与 `C1–C5` **共用同一张边界登记表**。
//!
//! # 成员怎么认：**文件自己说了算，登记表只是另一侧**
//!
//! 一份文件属于通信层，当且仅当它的文本里带着那枚标记 —— 逐字 `COMM-LAYER-MEMBER`，
//! 写在文件头的注释里（`.rs`/`.ts` 用 `//`，`.toml` 用 `#`）。
//!
//! 这样安排只为一件事：**恒等的两侧异源**。
//!
//! | 侧 | 住哪 | 谁写的 |
//! |---|---|---|
//! | 盘上那一侧 | 成员文件**自己的文本**（走 `guard_core::scan_tree_excluding` 现扫） | 把文件搬进来的那个人 |
//! | 登记那一侧 | `tests/bridge/comm_boundary_registry_tests.rs` 的 `REGISTERED` | 立表 / 改表的那个人 |
//!
//! 两侧做**两向集合相等**。四种失效各自当场红：
//! 带了标记却没登记（搬进来没人挡）· 登记了却找不到（路径漂了 / 标记被删了）·
//! 文件被移走 · 表被清空而盘上还有成员。
//!
//! ⚠ **这一条是主锚。** 判据自己文件里钉的那个数（`POPULATION_TODAY`）与 `REGISTERED`
//! **同源**：它只挡得住「改表时没想清楚」，挡不住「两边被同一次编辑一起改掉」。
//! 别把它当反空真的依据 —— 本仓逐字记过：「恒等两侧同源会退化成恒真」。
//!
//! # 〔现打·今天〕**登记在册的通信层成员：0 份**
//!
//! 人群为空。这句话**不是散文** —— 上面那个数由
//! `the_boundary_registry_says_out_loud_how_big_it_is_today` 每趟从本文件里抠出来，
//! 与盘上现扫的份数、与 `REGISTERED` 的长度做**三方相等**。
//! 搬进来一份而忘了改这句话 ⇒ 当场红；把这句话改大而盘上没有 ⇒ 也当场红。
//! ⇒ 「今天是空的」在终端上**说得出口**，而不是静默的一片绿。
//!
//! # 空集期那条绿，到底靠什么不是空转
//!
//! 三样，每趟都跑：
//!
//! 1. **相等断言**（上面那两条）—— 绿的理由是 `0 == 0`，不是「扫不到」。
//! 2. **语料见证**（`CORPUS_WITNESS`）—— 几个**逐字的真住址**必须出现在这一趟的扫描面里。
//!    扫描根写错、后缀过滤打空、排除名单摘过头，都会让它当场红。
//!    ⚠ 刻意**不用地板**（`>= N`）：地板在「变少」方向是瞎的，而本仓正是栽在那上面。
//! 3. **阳性对照**（每条判据各一份合成样本）—— 判据的识别器拿一段**故意有违例**的文本
//!    喂一遍，必须认出来；再拿一段干净文本喂一遍，必须不认。
//!    人群为空时，判据买到的**全部**就是这一条：「识别器今天是活的」。
//!
//! # 死值验 —— 十八刀逐刀红过（量于本拍 `4ce28af4`，快照不是常量）
//!
//! 「判据在」与「判据会红」是两件事。落地当天逐刀砍过一遍，每刀都**确认真的红**、
//! 再逐字节还原（`sha256` 对账，还原**不搬 mtime** —— 搬了 cargo 会读到上一刀的回声）：
//!
//! | 组 | 怎么砍 | 红了什么 |
//! |---|---|---|
//! | **C1–C5 · X1–X6**（11 刀） | 临时登记一份合成成员，往它里面注一处违例（业务词 / 业务 crate / 公开面上的 `transport` / 读盘 / 起进程 / 通配臂 / 期限字面量 / 缺 `reach` 的 `Hop` / 静默丢弃 / 放宽的 `until` / 无 `Budget` 的调用点） | **各只红它自己那一条**，零串扰、零漏网 |
//! | **A1** | 盘上冒出一份带标记的文件而不登记 | 锚 ＋ 散文 ＋ 十一条，共 13 条 |
//! | **A2** | 登记一条盘上不存在的路径 | 同上 13 条 |
//! | **A3** | 扫描面被改窄（后缀表只剩 `rs`） | 12 条（语料见证当场分叉）—— ⚠ 散文那条**没红**：它不看见证，挡这一形的是锚 |
//! | **A4** | 散文里的份数漂成 9，而表里 0 行 | 只红散文那一条（精确到一条） |
//! | **A5** | 语料排除名单悄悄失效（`/vendor/` 摘不到东西） | 13 条 |
//! | **A6** | 识别器被打瞎（恒 `false`），同时盘上真有一份成员 | 14 条（多的那条是识别器的阳性对照） |
//! | **A7 / A8** | 判据清单删一行 / 判据本体删一条 | 各只红元判据那一条（两个方向都查） |
//!
//! ★ **同拍的阴性对照**：登记一份**干净**的合成成员 ⇒ 十五条全绿。
//! 它买的是「这些判据不是一见到非空人群就红」—— 没有这一条，上面那十一刀证明不了什么。
//!
//! # 这张表买到什么 / 买不到什么（如实登记）
//!
//! **买到**：
//!
//! - 通信层的边界**有一张机检的表**，而不是「大家都知道它在哪」。
//! - 搬一份文件进来（给它盖标记）而不登记 ⇒ 当场红；登记一份不存在的 ⇒ 当场红。
//! - 十一条判据**在执行链上**（`monitor` 的 `cargo test --lib`，门禁 `cargo` 那一格），
//!   人群一非空就立刻开始收紧。
//!
//! **买不到**（别读大了）：
//!
//! - **不买「这份文件真的该属于通信层」** —— 标记是人盖的，盖错了本表照收。
//!   本表守的是「盖了标记的那批有人数着、有人挡着」，不是归属判断本身。
//! - **不买「没盖标记的文件不是通信层」** —— 一份传输代码不盖标记，本表**一个字都看不见**。
//!   这是本表最大的诚实边界：它挡的是**明着搬进来**的那条路，
//!   挡不住「在别处偷偷长出第二个通信层」。那一格今天**判不了**，
//!   缺的证据是一张「哪些文件在做传输」的独立读数（`设计/05 §9` 逐字：
//!   `ssh_source.rs` 那 8647 行未读 ⇒ 传输与业务混到什么程度判不了）。
//! - **`C1`–`C5` / `X1`–`X6` 各自买到什么、买不到什么**，逐条写在
//!   `tests/bridge/comm_boundary_registry_tests.rs` 每条判据自己的文档注释里 ——
//!   不在这里抄第二份（本仓 `E12`：一个数/一句话出现在两个地方就会漂）。
//!
