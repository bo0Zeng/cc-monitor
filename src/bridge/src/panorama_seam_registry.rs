///   它认不出来。它挡的是「多一处同名取用」，不是「改名逃逸」。
/// - **只到「哪一份文件里有」这一格**：本模块钉命中的**住址表**，
///   「那一份文件里恰好一次」由上面那条 `find_pinned` 钉 —— 两条合起来才是「全体恰好一次」。
