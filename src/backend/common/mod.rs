//! U2（2026-08-01）：**`common/` —— observe 与 control 两边都要、又不含平台原语的纯工具。**
//!
//! # 为什么 `platform`/`observe`/`control` 三分不够
//!
//! 计划自审 §0.5-6 打掉过我一处错：v1/v2 只写三分。实际 `projects_root` 有**四份逐字相同**的
//! 副本，其中 `fork_write.rs` 那份属 control、另三份属 observe —— 归哪边都不对，它谁也不属于。
//! 强行塞进 observe 会让 control 反向依赖 observe（回边），塞进 platform 更错（它不碰平台）。
//! ⇒ 加第四层。
//!
//! # 门槛（别让这里变成杂物间）
//!
//! 进 `common/` 要同时满足三条：
//! ① **≥2 个上层用**（按**层**数，不是按文件数）
//! ② **平台无关**（不含平台 cfg、不依赖某个 OS 的文件布局或 ABI —— 那是 `platform/` 的事）
//! ③ **无域知识**（不认识 `WatchEvent` / `ResumeSpec` 这类东西）
//!
//! 不满足就留在它自己的模块里 —— 「反正大家都可能用」不是理由。
//!
//! > **② 的措辞是 Phase D 审计订正的。** 我第一版写的是「**纯**（不 I/O 决策…）」，
//! > 而同一次提交放进来的 `mtime_ms` 第一行就是 `std::fs::metadata` —— **门槛被自己放进去的
//! > 函数当场破了**。门槛是防「杂物间」的唯一机制，第一条就自相矛盾会让它彻底失去约束力。
//! > 真正要挡的从来不是 I/O，是**平台知识**与**域知识**：`mtime_ms` 做 I/O 但对 OS 一无所知
//! > （`std::fs` 在哪都一样），它该在这里；`proc_starttime` 也做 I/O，但它认识 `/proc` 的字段
//! > 布局，它该在 `platform/`。
//!
//! > **那条登记项已结案（U3）**：`mtime_ms` 曾放在这里，而它的两个调用点同属 observe ⇒
//! > 按①的「层」口径不达标。U2 时 `observe/` 还不存在、判不了，我如实登记了「U3 必须复查」；
//! > U3 建出两层后一查确实不达标，**搬进了 `observe/fs.rs`**。
//! > 留一句在这里是因为**这是这三条门槛第一次真的把一个函数请出去** ——
//! > 门槛只有在写规则的人也照它办时才有约束力。

pub(crate) mod contract;
pub(crate) mod fs;
/// **后端建自家目录的那一个函数**（原住 crate 根 `own_dir.rs`）。
///
/// 它满足门槛的方式：①（≥2 层）原生那一块（退出行为 · 资产目录 · skill 装记录 · 中转钥匙 · 常驻登记）与
/// 文件管理那一块（暂存区，`control/files_commit.rs`）都建这一层 —— 两块之间零互相依赖（`files/module_boundary_guard.rs`），
/// 共用的只许在这一层。②（平台无关）unix 权限位那一句是 `std` 的扩展 trait，不是平台原语的读法。
/// ③（无域知识）它只认「建一层目录、只给本人」，不认那一层装什么。
/// ⚠ 它**写盘**（建目录）：`readonly_guard` 第四层照旧登记它（住址随搬家改成 `common/own_dir.rs`）。
pub(crate) mod own_dir;
/// **路径原始字节的线上两种形**（字符串 / `{"b16": …}`，原住 `files/raw.rs`）。
///
/// 它满足门槛的方式：①（≥2 层）文件管理那一块（整族入参 / 回送）与原生那一块（`dial/terminal.rs`：文件窗口「在此打开终端」
/// 交来的当前目录）都读这一形 —— 两块之间零互相依赖，共用的只许在这一层。②（平台无关）只做 JSON ⇄ 字节。
/// ③（无域知识）它只认「一串字节怎么上线」，不认那是哪个文件、拿去干什么。
pub(crate) mod path_wire;
/// `K-R96`（09-12）：**「这台机器上现在有哪些 tmux 会话」那一张快照。**
///
/// 它满足门槛的方式：①（≥2 层）**control 与 observe 都在用** ——
/// control 侧 `gate::list_sessions` 判活、`ccm` 铸名避让向它要 hash 表；
/// observe 侧 `watcher` 每观测一轮就把看到的那份焐进来。
/// 这一条是**真的两层**，不是「反正大家都可能用」：它住 `control/` 的话 watcher 要走一条
/// `observe → control` 的回边（`layering_guard` 数着条数），住 `observe/` 的话 Gate
/// 根本引用不到（那条边被钉死了）。
/// ②（平台无关）它起的是 `tmux` 这个跨平台程序，不认识任何 OS 的文件布局。
/// ③（无域知识）它只认识「会话名 + `@ccm_sid`」两个字段，不认识 `WatchEvent` / `Plan`。
pub(crate) mod session_snapshot;
/// `K-R12` 下一拍（09-04）：**「tmux 的打印通道必须是 UTF-8」这一个口径的家。**
///
/// 它满足门槛的方式与 `fs` 不同，值得在这里点一句：①（≥2 层）**只在
/// 「`-u` 与 `LC_ALL=C.UTF-8` 是一个口径的两种表示」这个读法下成立** ——
/// 当成两个口径去数，两个都只有一层在用、两个都不达标。
/// 那个读法有三条实测撑着（同一个开关 · `-u` 压在 env 之上 · 两者在调用点上不可互换），
/// 逐条在该模块头注里。⇒ 门槛没有被放宽，是被**答对了一问**才通过的。
pub(crate) mod tmux_utf8;
