//! # ⚠ `<account>` 那一段是 `K-H2` 加的，理由与代价逐条记这里
//!
//! `K11 裁定一`（现行版）那张表把上游端点归给**按路由键查的那张表**，并注明
//! 「**路由键带账号那一段**」（原文把那张表记在中转名下 —— 它今天是上游选择的 apikey 表）——**而在 `K-H2` 之前，路由键里没有那一段**：
//! `<agent>` 是 `K9` 裁定二要的「agent-aware 的路由键」，`<key>` 是会话 id 那一类。
//! ⇒ 加这一段是**照裁定做**，不是发明一个新维度。
//!
//! **为什么不复用 `<key>` 段**（`K-H2` `Bx` 判的，PM 08-28 采纳）：
//! 那会让 `<key>` 同时装会话 id 与账号 id ——**一个值装了两件事**，
//! 本工作区最贵的那族病。它今天不疼（tee 那条流零消费者），
//! 而它的代价是**将来才发作、发作时找不回原因**的一次回退。
//! 加一段的代价是**今天可数的**：本文件的 `parse` · 本文件的判据 ·
//! `src/doc/IPC-PROTOCOL.md` 那一行 · tee 的行契约。
//!
//! ⚠ **`<account>` 段本身不保证那个账号存在** —— 它只保证「形状对得上」。
//! 「表里有没有这一行」是上游选择（`accounts::table`）的活，查不到就是 **404**
//! （`K-H2` `KH2`：不许回落到别的账号的 key，也不许回落到默认上游）。

/// 切出来的路由。`rest` 逐字保留原请求的 `路径 + 查询串`，中转不重写它。
///
/// # 🔴 条 48（2026-09-18 拍板 (a)）：这几个字段**用位置名，不用业务名**
///
/// 先前它是 `{ agent, account, key }` 三个业务名。今天是
/// `{ mode, key: RouteKey{seg1,seg2}, rest }` —— 中转只知道「第 1/2 段」，整包交给上游选择当键
/// （〔V141〕第 3 段退役）。
/// 谁是 agent、谁是账号，**只在 `accounts/` 那一层才有这两个词**。
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct Route {
    /// 哪个前缀进来的 —— `/s/` 代入 · `/t/` 直通。中转只转交，不解释。
    pub(crate) mode: super::Mode,
    /// 前两段，整包交给上游选择当键。中转**不解释**它们。
    pub(crate) key: super::RouteKey,
    pub(crate) rest: String,
}

/// 一段路由键里允许的字符 —— 白名单，不是黑名单（ASCII 字母数字与 `-` `_`，1..=128 字节）。
///
/// 收窄到这几类是**故意的**：路由键要参与日志与 tee 行，放开任意字节等于给
/// 「把控制字符 / 换行塞进 tee 流」开一条路。`.` 与 `/` **不在**白名单里 ⇒ `..` 这种段根本构造不出来。
///
/// ★ 同一条性质只许有一个实现〔`K-H2`〕：装路由表时判「这个账号 id 当得了路由段吗」与本函数问的是同一个问题。
/// 〔US1 · 4D〕它与两个前缀、拼 / 拆路由一起住共享 crate `relay_route_core`（`设计/20 §5` 目标）：
/// monitor 那一侧（起会话身份 token · 载荷里中转地址的校验）与这里 `use` 同一份，先前的「两侧各写一份、样例对拍」退役。
/// 那个 crate 不是业务 crate（没有账号 / 凭据的名字），本文件是通信层成员也可以依赖它（`05 §2` `C2`）。
pub(crate) use relay_route_core::segment_is_safe;

/// 解析 `/<前缀>/<seg1>/<seg2>/<rest>`。不是这个形状就返回 `None`（调用方回 404）。
/// 〔US1〕前缀闭集与切法住 `relay_route_core::parse_target`（唯一住址）；本函数只把共享 crate 的模式
/// 换成中转自己的契约类型 `super::Mode`（上游选择收的是它）。
pub(crate) fn parse(target: &str) -> Option<Route> {
    let p = relay_route_core::parse_target(target)?;
    Some(Route {
        mode: match p.mode {
            relay_route_core::RouteMode::Substitute => super::Mode::Substitute,
            relay_route_core::RouteMode::Passthrough => super::Mode::Passthrough,
        },
        key: super::RouteKey {
            seg1: p.seg1.to_string(),
            seg2: p.seg2.to_string(),
        },
        rest: format!("/{}", p.rest),
    })
}

