//! 路由：从请求路径里切出**路由键**，把其余部分原样交给上游。
//!
//! 形状 `/<前缀>/<seg1>/<seg2>/<seg3>/<真路径>` —— 三段都是**不透明串**。
//! 中转不认识任何 agent 叫什么，也不解释 `<seg3>` 是会话 id 还是别的什么。
//!
//! # 🔴 通信层成员 `COMM-LAYER-MEMBER`〔`设计/05 §8` 步 4，2026-09-21〕
//!
//! 这一枚标记是**盘上那一侧**的凭据（登记那一侧在
//! `tests/bridge/comm_boundary_registry_tests.rs::REGISTERED`，两向集合相等）。
//! 盖上它 = **上锁**，不是放行：本文件从此被 `C1`–`C5` ＋ `X1`–`X6` 十一条一起管着。
//!
//! **凭什么它属于通信层**：`设计/05 §2` 逐字列的四样里第一样是「**地址**（`origin` /
//! 路由键）」，而本文件就是**面 B 那一侧的路由键**本体。更要紧的是，它是
//! `设计/01 §2.1` 那条「🔴 怎么做到零豁免」的**现物** —— 逐字：「通信层的类型里用
//! **位置**称呼它搬的东西（「路径的第 1/2 段」＋一个不透明的流标签），业务名只出现在
//! 后端那一半的实现里」。下面那个 [`Route`] 与 `super::RouteKey{ seg1, seg2 }` 就是它
//! （条 48 · 形状的唯一住址是 `设计/20 §0`/`§2`）。
//!
//! ⇒ 本文件**只切键、不解释键**：谁是 agent、谁是账号只在 `accounts/` 那一层才有名字。
//! 十一条对它现打全绿 —— 它是 `§8` **步 4**（「通信层改成『收一张表』」）圈得进来的那两份之一。
//!
//! ⚠ **别把它读成「`relay/` 整层进来了」**：同目录七份里今天只有本文件与 `http1.rs`
//! 进得来，其余五份各被哪几条咬住、为什么，逐份读数住 `真相源/`（`E12`：一个事实一个住址，
//! 不在这里抄第二份）。
//!
//! # 🔴 两个前缀 = 两种模式（`设计/20 §2`「为什么用两个前缀而不是一个哨兵段」）
//!
//! ```text
//! /s/…  代入模式：表里必须有这一行，没有 ⇒ 404（`K-H2` `KH2` 那条语义，一字不改）
//! /t/…  直通模式：中转**永不**代入 auth；`seg2` 只当标签
//! ```
//!
//! **意图写在线上**，两条路不可能互相静默降级。如果用一个前缀 ＋「查不到就直通」，
//! 那么**一次 `seg2` 打字错误**就会从「该代入却没代入（loud 404）」变成
//! 「**静默用了下游自己的凭据**」—— 那正是 `KH2` 在治的病的镜像。
//! 两个前缀把这件事变成**构造上不可能**：`/s/` 永远 fail-closed，`/t/` 从来不代入。
//!
//! ⚠ **四个槽位一格没动** ⇒ [`segment_is_safe`] 一字不改，`parse` 只多剥一次前缀
//! （`20 §0`：线格式本来就是对的，要动的只是中转怎么称呼它们）。
//!
//! ⚠ **今天没有任何人往 `/t/` 上发流量** —— 注入侧仍然只拼 `/s/`
//! （`payload.rs::RELAY_ROUTE_SAMPLE`，本文件那条跨半边对拍判据现读它）。
//! 打开注入是 `99 §4` 的 **14-ii**，而且逐字要求「**必须带开关，默认关**」。
//!
//! # ⚠ `<account>` 那一段是 `K-H2` 加的，理由与代价逐条记这里
//!
//! `K11 裁定一`（现行版）那张表把上游端点归给**按路由键查的那张表**，并注明
//! 「**路由键带账号那一段**」（原文把那张表记在中转名下 —— 它今天是上游选择的 apikey 表）——**而在 `K-H2` 之前，路由键里没有那一段**：
//! `<agent>` 是 `K9` 裁定二要的「agent-aware 的路由键」，`<key>` 是会话 id 那一类。
//! ⇒ 加这一段是**照裁定做**，不是发明一个新维度。
//!
//! **为什么不复用 `<key>` 段**（`K-H2` `Bx` 判的，PM 08-28 采纳）：
//! 那会让 `<key>` 同时装会话 id 与账号 id ——**一个值装了两件事**，
//! 本工作区最贵的那族病。它今天不疼（tee 那条流零消费者），
//! 而它的代价是**将来才发作、发作时找不回原因**的一次回退。
//! 加一段的代价是**今天可数的**：本文件的 `parse` · 本文件的判据 ·
//! `src/doc/IPC-PROTOCOL.md` 那一行 · tee 的行契约。
//!
//! ⚠ **`<account>` 段本身不保证那个账号存在** —— 它只保证「形状对得上」。
//! 「表里有没有这一行」是上游选择（`accounts::table`）的活，查不到就是 **404**
//! （`K-H2` `KH2`：不许回落到别的账号的 key，也不许回落到默认上游）。

/// 切出来的路由。`rest` 逐字保留原请求的 `路径 + 查询串`，中转不重写它。
///
/// # 🔴 条 48（2026-09-18 拍板 (a)）：这几个字段**用位置名，不用业务名**
///
/// 先前它是 `{ agent, account, key }` 三个业务名。今天是
/// `{ mode, key: RouteKey{seg1,seg2}, stream }` —— 中转只知道「第 1/2/3 段」，
/// 把前两段整包交给上游选择当键、把第 3 段当自己那条流的名字。
/// 谁是 agent、谁是账号，**只在 `accounts/` 那一层才有这两个词**。
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct Route {
    /// 哪个前缀进来的 —— `/s/` 代入 · `/t/` 直通。中转只转交，不解释。
    pub(crate) mode: super::Mode,
    /// 前两段，整包交给上游选择当键。中转**不解释**它们。
    pub(crate) key: super::RouteKey,
    /// 第 3 段 —— 中转自己那条流的名字（它是 sid，但中转不需要知道）。
    pub(crate) stream: String,
    pub(crate) rest: String,
}

impl Route {
    /// 这一条请求在 tee 上的身份。**三个标签收成一个**（`20 §4`）。
    pub(crate) fn stream_id(&self) -> super::StreamId<'_> {
        super::StreamId {
            key: &self.key,
            stream: &self.stream,
        }
    }
}

/// 一段路由键里允许的字符 —— 白名单，不是黑名单。
///
/// 收窄到这几类是**故意的**：路由键要参与日志与 tee 行，放开任意字节等于给
/// 「把控制字符 / 换行塞进 tee 流」开一条路。`.` 与 `/` **不在**白名单里 ⇒
/// `..` 这种段根本构造不出来。
///
/// ★ 它是 `pub(crate)` 的，理由是**同一条性质只许有一个实现**〔`K-H2`〕：
/// 装路由表的时候要判「这个账号 id 当得了路由段吗」，那与本函数问的是
/// **同一个问题**。两边各写一份，漂开的那天没有任何东西会说，
/// 而症状是「文件里配了一条账号，请求永远 404」这种查不出来的形状。
pub(crate) fn segment_is_safe(seg: &str) -> bool {
    !seg.is_empty()
        && seg.len() <= 128
        && seg
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

/// 两个前缀 ＋ 它们各自的模式。**闭集，唯一住址** —— 散文里不许再抄一份
/// （`brief` 13b）。要印出来就现算这张表。
const PREFIXES: &[(&str, super::Mode)] = &[
    ("/s/", super::Mode::Substitute),
    ("/t/", super::Mode::Passthrough),
];

/// 解析 `/<前缀>/<seg1>/<seg2>/<seg3>/<rest>`。不是这个形状就返回 `None`（调用方回 404）。
///
/// ⚠ 四个槽位**一格没动**（`20 §0`：线格式本来就是对的），动的只是中转怎么称呼它们。
/// ⇒ `segment_is_safe` 一字不动，`parse` 只是多认一个前缀、并把模式一起交出去。
pub(crate) fn parse(target: &str) -> Option<Route> {
    let (mode, after) = PREFIXES
        .iter()
        .find_map(|(p, m)| target.strip_prefix(p).map(|rest| (*m, rest)))?;
    let (seg1, after) = after.split_once('/')?;
    let (seg2, after) = after.split_once('/')?;
    let (seg3, rest) = after.split_once('/')?;
    if !segment_is_safe(seg1) || !segment_is_safe(seg2) || !segment_is_safe(seg3) {
        return None;
    }
    Some(Route {
        mode,
        key: super::RouteKey {
            seg1: seg1.to_string(),
            seg2: seg2.to_string(),
        },
        stream: seg3.to_string(),
        rest: format!("/{rest}"),
    })
}

