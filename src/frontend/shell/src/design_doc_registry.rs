//! **设计篇的索引不许与各篇自己的声明漂**〔`设计/99 §4.17` · `Q9` 乙，2026-09-23〕。
//!
//! # 为什么有这一条：那份索引**自己撒过谎**，而没有任何东西会红
//!
//! `调研/README.md` 的设计篇索引是所有人读设计的第一站。2026-09-23 全面整理时逐处现打，
//! 它腐了**至少 4 处**，其中最贵的一处是：它把一篇**整篇作废**的文档标成「**已定**」。
//!
//! 🔴 **那一处的后果是结构性的，不是排版问题**：正文腐了，读者还有机会读出矛盾；
//! **索引腐了，他根本不会去读那一篇** —— 于是任何按索引挑活的人都会去读一篇死文档，
//! 而那篇死文档的正文从第一行起就喊着「我作废了」。
//!
//! ⇒ 本条把「索引与各篇自己的声明必须一致」从一次人工整理变成**会红的判据**。
//!
//! # 它判什么（两向，都是集合相等／零命中，一个地板都没有）
//!
//! | 判词 | 形状 |
//! |---|---|
//! | 索引点名的篇 ↔ 盘上 `调研/设计/*.md` | **两向集合相等** |
//! | 索引标「整篇作废」的篇 ⇒ 那篇自己必须声明作废 | 逐篇，零漏 |
//! | 那篇自己声明了作废 ⇒ 索引必须标「整篇作废」 | **反向那一半 —— 它才是治那个病的** |
//! | 抠得到状态栏、人群非空 | 反空真自检；抠不到就**拒绝出数**，不是当成绿 |
//! | 〔D0b〕每一行的状态格落进 ✅／⚠／🚫 之一 | 落不进的行集 == ∅ |
//! | 〔D0b〕标 ⚠ 的篇 ⇒ 篇内至少一块作废块 | 违例集 == ∅ |
//! | 〔D0b〕标 ✅ 的篇 ⇒ 篇内零作废块 | 违例集 == ∅ —— ⚠ 今天 `#[ignore]`，解锁条件住那条判据头上 |
//!
//! # 〔D0b · 第四波 2026-09-24〕「作废块」是一条**契约**，不是语义猜测
//!
//! 块首行 ＝ ATX 标题行（含 `> # …`）或一段引用的第一行（围栏代码块里的不算）；
//! 可见文字（剥掉行内代码）里含「作废」「推翻」「订正」「腐」之一 ⇒ 作废块。
//! ⇒ **这四个词在标题行与引用块首行里是保留字**，只用来标作废／订正块。
//! 为什么定成保留字而不是去读语义、为什么多了个「腐」、设计当天对真 `调研/` 的读数：
//! 住 `调研/第四波记录/D0b.md`（主会话并进设计篇之前的唯一住址）。
//!
//! # 🔴 `调研/` 是**给定的** —— 找不到就红，不是跳过
//!
//! 这一条与 `设计/01 §5 D11`（「后端是给定的，不许为『它可能没起来』留退路」）同形，
//! 依据也一样具体：本仓只有一个用户，两台机器靠 Resilio 同步同一棵 `~/文档/`
//! ⇒ `调研/` 缺席不是一种要伺候的常态，**它是坏了**。
//!
//! ⚠ **代价如实认下**：哪天有人只 clone `cc-monitor` 而不带 `调研/`，这一格会红。
//! 那时候正确的处置是**把 `调研/` 带上**，不是给这一条开豁免 ——
//! 因为一旦开了，索引就回到「腐了没人出声」的状态，而那正是它存在的理由。
//!
//! # 它**买不到**什么（逐条，别读宽）
//!
//! - **不买「索引那一栏的描述是对的」** —— 它只判**状态**（活／部分作废／整篇作废）这一维。
//!   一篇标着 ✅ 活而正文其实半死，本条一个字都不说。
//! - **不买「⚠ 那几节标全了」** —— 〔D0b 起〕⚠ 那一档只判到「篇内至少有一块作废块」、
//!   ✅ 那一档只判到「篇内一块都没有」。一篇有一块就过；它里面还有没标的死节，本条不说话
//!   （哪一节死了要读语义，机器判不动）。
//! - **不买「真相源那一族」** —— 那 42 篇的规矩是「过期了就重打，不要转述」，与索引这一维正交。

