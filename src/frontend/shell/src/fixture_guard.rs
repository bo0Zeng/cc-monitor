//! **夹具不许变成孤儿**〔`99 §4.8.3 P15`，`α3` 刀 D 那个没红的读数〕。
//!
//! # 病：`tests/__fixtures__/` 这一格今天零判据
//!
//! `α3`（09-21）在删用量那一轴时撞见一件事，写进了它的读数：
//! `设计/50 §2` 的整删清单把那份用量夹具的住址写成了 `src/__fixtures__/`，
//! 而仓库重组（`设计/16`）早把那个目录搬成了 `tests/__fixtures__/`
//! ⇒ **09-18 那一刀按旧住址删，于是删了一个不存在的文件，真文件静默留在盘上**，
//! 一直活到 09-21 才被顺带撞见。
//!
//! 🔴 **两个独立的坏后果，第二个更要紧：**
//!
//! 1. 那份夹具的正文是**真采的账号用量输出、含真金额** ——
//!    撞本仓那条「测试夹具采结构不采内容」的纪律。
//! 2. **它凭什么能静默活三天**：那一格**没有任何判据**。
//!    一份夹具掉光全部引用之后，盘上没有一样东西会因此变红 ——
//!    既不因为「没人在用它了」，也不因为「它本该随被测面一起没了」。
//!    `α3` 刀 D 就切在这一格上：往 `tests/__fixtures__/` 放一份零引用的夹具，
//!    **一条判据都没红**（本件基点现打复验过，读数写在下面）。
//!
//! ⇒ 第 1 条是一次性的清理，第 2 条是**机制**。本模块只做第 2 条。
//!
//! # 现打（2026-09-22，本件基点 `d8074d9c`）
//!
//! - 盘上夹具 **1 份**（`tests/__fixtures__/scale2-height-records.jsonl`）；
//! - 它的**活引用 10 处 / 5 份文件**，全是 `.ts`（四套秤的 vitest ＋ 一份共用语料构造器）；
//! - 全仓搜「孤儿 / 未引用」这一族的判据：**零命中**（不截断的 `grep`，
//!   `.rs` / `.ts` / `.sh` 三族都搜过）。唯一提到这个目录的守卫是
//!   `tests/frontend/ui/settings/base-wording-guard.vitest.ts`，而它是**把这个目录跳过**的。
//! - 死值验：`tests/__fixtures__/` 下放一份零引用的 `.jsonl`
//!   ⇒ `cargo test -p monitor --lib` **1753 passed / 0 failed**，一格没红。
//!
//! # 它买到什么
//!
//! 两个方向，各自是一条**相等**（不是地板 —— 地板在「变少」方向上是瞎的，
//! 而「夹具掉光引用」正是变少那个方向）：
//!
//! | 方向 | 人群 | 相等断言 |
//! |---|---|---|
//! | 甲 | **盘上每一份夹具**（那个目录的文件系统全集） | 孤儿集 ＝ 豁免登记表 |
//! | 乙 | **活树里每一处夹具地址** | 悬空集 ＝ 悬空登记表 |
//!
//! 方向乙是甲的镜像，收的是另一半：**代码里点着一份盘上没有的夹具**。
//! 它同时给本条一个**非空**的第二人群 —— 甲那一侧的豁免表今天是空的，
//! 一条只有空表的判据说不出「反向那半还在不在」。
//!
//! # 🔴 它买不到什么（逐条写明，别把射程写宽了一格）
//!
//! - **判不了夹具的正文对不对。** 「采结构不采内容」「不许含真会话正文 / 真金额」
//!   要读内容语义，本条一个字节都不读夹具正文。⚠ 那条纪律今天**仍然没有机检**
//!   （现打：全仓零判据），如实记在这里，不假装本条覆盖了它。
//! - **「活引用」按名字认，不按可达性认。** 一处引用只要在活树的一份非散文文件里
//!   写出了那个基名就算活的。判不了那份文件今天还跑不跑、那一行还执行不执行
//!   —— 那要读语义（`α3` 顺带逮到的 tier-2 那条潜伏红就是这一形）。
//! - **基名撞车时它偏向不红。** 夹具起成 `data.json` 这种短名的话，随便一句散文
//!   都能让它显得「有人在用」。本条不猜、也不替人改名；处置是**把夹具起成不会撞的名字**。
//! - **只看 `tests/__fixtures__/` 这一个目录。** 别处的夹具（各判据自己 `include_str!`
//!   进来的那些）不在人群里 —— 那些有编译器兜着（引用没了就是死码 / 文件没了就编不过），
//!   而本目录里的夹具是**按路径在运行期读**的，编译器一个字也管不了。
//!   这正是这一格为什么单独需要一条判据。

/// 夹具目录的**唯一住址**（仓根相对，`/` 分隔）。判词文件里不抄第二份。
pub const FIXTURE_DIR: &str = "tests/__fixtures__";

/// **纯散文**的扩展名 —— 这几族不算活引用来源。
///
/// 理由一句话：**一句话读不了一份夹具。** 一份夹具被记录 / 报告 / 设计稿点过名，
/// 不等于今天有东西在用它；而 `α3` 那份孤儿夹具恰恰就是**只**被记录点着的。
///
/// ⚠ 代价如实写明：一份夹具若真的只从散文里被引用，本条会判它孤儿。
/// 那不是误红 —— 那种夹具本来就该删掉或者接上一条判据。
/// 现打：盘上那份夹具的 10 处活引用**全是 `.ts`**，这一刀今天一处都不误红。
pub const PROSE_EXTENSIONS: &[&str] = &[".md", ".txt"];

/// [`FIXTURE_DIR`] 的**末段**（`__fixtures__`）—— 方向乙的针从这里运行期拆。
///
/// 为什么不写第二份字面量：本仓真实的引用写法有三形（`__dirname` 拼的
/// `"__fixtures__/…"` · `"../__fixtures__/…"` · 散文里写全的
/// `tests/__fixtures__/…`），它们的**共同前缀**只有这个末段。
/// 写死一份字面量就等于给同一个地址开了第二个家，而本仓 `E12` 整条在治这一族。
pub fn fixture_dir_leaf() -> &'static str {
    FIXTURE_DIR.rsplit('/').next().unwrap_or(FIXTURE_DIR)
}

/// 递归枚举 `dir` 下**每一个文件**，给出 `root` 相对路径（`/` 归一、排序）。
///
/// # 🔴 为什么不能走 [`guard_core::scan_tree_excluding`]
///
/// 那个共享原语收的是**文本语料**：它的头注逐字写着「读不动 ＝ panic；
/// **不是文本 ＝ 跳过**」，理由是「一个非 UTF-8 的字节流不可能含调用方要找的
/// 那些标识符 ⇒ 跳过它零损失」。那句话对它所有既有调用方都成立，对本条**恰好相反** ——
/// 本条的人群是**夹具文件本身**，而一份孤儿夹具完全可以是二进制
/// （截图 / 压缩过的记录 / 二进制快照）。走那条原语的话，
/// **二进制孤儿按构造看不见**，而「看不见」与「没有」在输出上一模一样。
///
/// ⇒ 这里只取**路径**，一个字节都不读，于是二进制夹具照样进人群。
/// `the_fixture_scanner_can_tell_an_orphan_from_none` 把这一条钉成了机检：
/// 同一个真目录（仓里那一堆图标）本函数与那个原语给出的份数**必须不相等**。
/// 哪天原语补了字节档，那一格会红，届时本函数就该退役 —— 别让它留着替原语挡枪。
///
/// ⚠ 本函数是**生产侧访问器**，不是测试钩子。`scanning_guard_registry` 那条递减棘轮
/// 逐字管的是「**测试段**里不许再出现裸的目录遍历」；把这一步搬进共享原语是
/// 「补原语的能力」那一拍（空扩展名那一档就是那么补的），不在本拍的写区里。
///
/// # Panics
///
/// 目录读不了时 panic —— 守卫语义照旧：读不到不许当成「里面没有东西」。
pub fn files_under(dir: &std::path::Path, root: &std::path::Path) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    if !dir.is_dir() {
        return out;
    }
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        let rd = match std::fs::read_dir(&d) {
            Ok(rd) => rd,
            Err(e) => panic!("读目录 {d:?} 失败: {e} —— 读不到不许当成「里面没有夹具」"),
        };
        for entry in rd {
            let path = entry.expect("dir entry").path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            out.push(
                path.strip_prefix(root)
                    .unwrap_or(&path)
                    .to_string_lossy()
                    .replace('\\', "/"),
            );
        }
    }
    out.sort();
    out
}

/// 这份文件（`root` 相对路径）算不算一处**活引用**的来源。
///
/// 三条排除，每条都有自己的理由，一条都不是「顺手」：
///
/// · **夹具目录自己** —— 夹具互相点名不叫「有人在用」。
/// · **`tests/evidence/`** —— 那是**量具与记录**（`dead_name_corpus` 头注逐字这么叫它）。
///   🔴 **这一条是承重的**：09-21 删掉的那份含真金额的孤儿夹具，在 `tests/evidence/`
///   里被点名 **3 处**（一份剪切脚本 ＋ 一份死值验记录 ＋ 一份读数）。
///   把这一棵算进活引用，本条对**那个活体**按构造就是瞎的 ——
///   而它正是 `P15` 点名要逮的那一个。
/// · **纯散文**（见 [`PROSE_EXTENSIONS`]）—— 理由在那张表上。
///
/// ⚠ 这三条是**明写的**排除，不是靠位置生效的。`设计/16 §5.4b` 纪律 2 逐字：
/// 「把靠位置的排除换成明写的排除 —— 位置会变，那一行不会」。
/// 判词那边还会另外**明写摘掉本模块与它自己那两份文件**，理由与这里不同
/// （那是「判据不许给自己投票」，见判词里那一段）。
pub fn counts_as_live_reference_site(rel: &str) -> bool {
    if rel.starts_with(FIXTURE_DIR) {
        return false;
    }
    if rel.starts_with("tests/evidence/") {
        return false;
    }
    !PROSE_EXTENSIONS.iter().any(|e| rel.ends_with(*e))
}

/// 一份夹具在 `text` 里**被点到了**吗？按**基名**认。
///
/// # 为什么按基名，不按整条仓根相对路径
///
/// 现打（2026-09-22）：盘上唯一那份夹具的 10 处活引用里，
/// 一处也没有写全 `tests/__fixtures__/…` —— 4 处是 `__dirname` 拼的
/// `"__fixtures__/…"`、2 处是 `"../__fixtures__/…?raw"`、其余是散文里的提法。
/// ⇒ 按整条路径认的话本条在真树上**零命中**，于是「没有孤儿」这个结论
/// 来自「一个都没认出来」。基名是这几种写法的**共同后缀**。
///
/// ⚠ 代价见本模块头注那条「基名撞车时它偏向不红」。
pub fn is_named_in(basename: &str, text: &str) -> bool {
    text.contains(basename)
}

/// 枚举 `text` 里每一处**夹具地址**，给出它点的那个基名（去重、有序）。
///
/// 口径：[`fixture_dir_leaf`] 之后紧跟一个 `/`，再往后吃一个路径 token
/// （`[A-Za-z0-9._-]`）。**空 token 不收** —— 那是在指这个**目录**
/// （`mkdirSync(…"tests/__fixtures__")` / 一条正则里的 `/__fixtures__/`），
/// 不是在指某一份夹具。现打：不排掉的话真树上会多出 4 处空地址，
/// 而它们一份文件都指不出来 ⇒ 那不是悬空，是**误采**。
pub fn fixture_addresses(text: &str) -> Vec<String> {
    let leaf = fixture_dir_leaf();
    let mut out: Vec<String> = Vec::new();
    let mut from = 0usize;
    while let Some(k) = text[from..].find(leaf) {
        let at = from + k + leaf.len();
        from = at;
        let rest = &text[at..];
        let Some(rest) = rest.strip_prefix('/') else {
            continue;
        };
        let tok: String = rest
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))
            .collect();
        if !tok.is_empty() {
            out.push(tok);
        }
    }
    out.sort();
    out.dedup();
    out
}

