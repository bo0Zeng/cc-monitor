//! # 人群非空之后，那条绿的理由变了一半（前一半没变）
//!
//! 空集那天，绿的理由是 `0 == 0` ＋ 识别器的阳性对照。今天是**三方相等**（上面那个 N），
//! 而人群里每一份都**真的被十一条扫过**。三样仍然每趟都跑：
//!
//! 1. **相等断言**（两向集合 ＋ 三方计数）—— 绿的理由是 `N == N`，不是「扫不到」。
//!    ⚠ 这一节刻意**不再写死那个数**：它先前逐字写着 `2 == 2 == 2`，而步 4 把人群改到 4 之后
//!    那三处成了假数，且**没有任何判据会红**（散文那一条只钉「登记在册…N 份」那一句）。
//!    ⇒ 一个数一个住址（`E12`）。
//! 2. **语料见证**（`CORPUS_WITNESS`）—— 几个**逐字的真住址**必须出现在这一趟的扫描面里。
//!    扫描根写错、后缀过滤打空、排除名单摘过头，都会让它当场红。
//!    ⚠ 刻意**不用地板**（`>= N`）：地板在「变少」方向是瞎的，而本仓正是栽在那上面。
//!    ⚠ 人群非空之后它**更**要紧，不是更不要紧：扫描面一打空，盘上那一侧会掉到 0，
//!    而 `REGISTERED` 还是那 N 行 ⇒ 主锚当场红。见证那一条负责说清**为什么**掉到 0。
//! 3. **阳性对照**（每条判据各一份合成样本）—— 判据的识别器拿一段**故意有违例**的文本
//!    喂一遍，必须认出来；再拿一段干净文本喂一遍，必须不认。
//!    人群为空时，判据买到的**全部**就是这一条；今天它退成「识别器还活着」的兜底，
//!    **不许删** —— 人群哪天又回到 0，它就又是唯一还在说话的东西。
