//! ⚠ **这一条是主锚。** 下面那句散文里钉的份数是**第三条腿**，不是主锚 ——
//! 它与 `REGISTERED` 多半由同一个人在同一拍写下，只挡得住「改表时漏改一处」，
//! 挡不住「两边被同一次编辑一起改掉」。
//! 别把它当反空真的依据 —— 本仓逐字记过：「恒等两侧同源会退化成恒真」。
