//! `backend/observe/` —— **读面**（§1.1 的能力线在 monitor 侧的另一侧）。
//!
//! 〔`K-R71` 09-12 建。**这个目录不是新写的一层，是把一个走错门的住户领回家**：
//! 它的第一个住户 `local_query.rs` 从 F10a 起就住在 `control/` 下，
//! 而它自己的头注第一句逐字写着「daemon 的**读面**是 14 条一次性查询子命令」。〕
//!
//! # 为什么今天才建，以及「只建一个空目录是装饰」那条反对理由为什么不再成立
//!
//! `backend/mod.rs` 头注记着这个决定的整段病史（墓碑两段 ＋ 三条「它已经被叫醒了」）。
//! 这里只留承重的那一句：**本目录一建出来就有真住户** ——
//! 搬进来的是**已经在生产段上被调用**的传输层（`usage.rs` 与 `local_accounts.rs` 都在调它），
//! 不是「先占个坑等以后」。⇒ 这是**搬运**，不是装饰。
//!
//! # 什么该进来：**按用途分，不按读写分**（`src/doc/ARCHITECTURE.md` §2.2）
//!
//! - **任何改状态的 tmux 命令**一律归 `control/`；
//! - **只喂控制决策的只读查询也归 `control/`**（daemon 侧 `control/gate.rs` 探 `@ccm_sid`
//!   就是这一形 —— 它不产观测帧）；
//! - **只有产出观测帧的读**才归这里。
//!
//! ⚠ 反面很具体，`src/doc/ARCHITECTURE.md` §2.2 逐字：按「读/写」分的话，那次 `@ccm_sid` 探测
//! 会被判给 `observe/`，而它唯一的调用方在 `control/` ⇒ **凭空造出一条
//! `control → observe` 的边**，而 daemon 侧的 `layering_guard` 逐字禁止反向依赖。
//!
//! ★〔`K-R73` 09-12〕**这句话在 monitor 侧从今天起也有机器在管**：`backend/mod.rs` 的
//! `layering` 模块照 daemon 的形立了两条 —— 反向（`control → observe`）零容忍，
//! 正向（`observe → control`）许有但逐条列举、条数被等号钉住。
//! ⇒ 上面那条「按读写分会凭空造出反向边」的反面，现在会**当场红**，不再只是一句叮嘱。
//!
//! # 🔴 本目录**今天只住着传输那一跳**，不许读成「本机读面已经搬完了」
//!
//! monitor 侧那 8 条还没退役的 `reader`（`config_surface.rs` · `search.rs` · `tasks.rs` …）
//! **一条都没有搬进来**，账在 `local_read_surface_registry` 的棘轮上。
//! 挡着它们的是两样有名有姓的东西（daemon 侧查询集缺口 · `tasks.rs`/`search.rs` 的宿主耦合），
//! 逐条写在 `backend/mod.rs` 头注最后一节。
