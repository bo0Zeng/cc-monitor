//! `K-H1` 甲半：**HTTP 中转 · 搬字节**。纯基础设施 —— 它不懂任何 agent 的语义。
//!
//! # 它做四件事（`K9` 裁定二那四条硬要求，逐字）
//!
//! 1. **一个进程** —— 一个监听面服务 N 个会话，不是每会话一个。
//! 2. **按路径前缀分流** —— 路由键塞在 base URL 的路径里（`/s/<agent>/<key>/<真路径>`）。
//! 3. **逐块透传绝不缓冲** —— 上游每给一块就立刻写下游并 flush，从不攒整个响应体。
//!    这是本方案**唯一真正的技术点**：缓冲了 TUI 会卡住不出字。
//! 4. **一边流回 CLI 一边 tee** —— 同一批字节既原样写回下游，又抄一份进 tee 流。
//!
//! # 三条**有意的偏离**，别当成移植漏了
//!
//! ## ㈠ tee 落在 **stdout**，不是文件（`裁-2` 在今天的代码上做不到）
//!
//! `裁-2`（PM 08-25）要 tee 走「每次响应一个新文件（`O_EXCL` 新建）」，理由是
//! 「新建一个此前不存在的文件不违反只读判据」。**那句话住在只读护栏的白名单层头注里，
//! 而白名单层只作用于唯一一个模块**（一个按仓库相对路径全等匹配的 `&str` 常量）。
//! 本模块落在**默认层**，而默认层的模式表把「以选项方式打开」与「新建句柄」那两个
//! 标准库入口的名字整个禁掉了 —— 标准库里「O_EXCL 新建」的每一种写法都含其中之一。
//! ⇒ 「判据一个字节不动」与「本模块自己新建文件」**不可能同时成立**。
//!
//! ⚠ 上一段**刻意不写出那两个入口的字面名字**：只读护栏是子串扫描、**不剥注释**，
//! 把它们原样写进注释，本模块会被自己的文档判成违规（写这份注释的第一版就是这么红的，
//! 而 `control/fork_write.rs` 的头注早把这条纪律逐字写着：**要改就改措辞，别去放宽护栏**）。
//!
//! 三条能绕开子串扫描的写法（把调用放进那个白名单模块 / 用类型别名改写调用 /
//! 直接走 `libc` 的系统调用）**一条都不走**：它们守住了护栏的字面、守不住它的意图。
//! ⇒ 本轮 tee 写 **stdout**，那是护栏头注逐字承认的唯一合法写。
//! 上层要落文件就重定向 —— 文件由**启动方**创建，本进程一个字节也不写文件系统。
//!
//! ## ㈡ 每行**不带 `t_ns`**（`裁-3`）
//!
//! 参考实现每行带一个跨响应单调的 `t_ns`（`Instant::now` 的等价物），而
//! `Instant::now` 在零定时器护栏的禁用清单里**且没有登记口**。⇒ 第一刀不带它。
//! **如实说这丢了什么**：`t_ns` 在参考实现里是一条**修过的 bug**（跨响应单调），
//! 不带它 = 暂时放弃那个修复面 ⇒ **任何要按时间对齐 tee 行的下游都得等这条解锁**。
//! 解锁条件：真出现需要它的消费者时，单独立一件去处置那个守卫。
//!
//! ## ㈢ 上游 `Accept-Encoding` 收窄成 `identity`，不是 `gzip`
//!
//! 参考实现收窄成 `gzip` 并自己流式解压，因此要一条解压依赖。Rust 重写改成收窄成
//! `identity`：tee 侧拿到的直接是明文 SSE，**整条解压依赖不需要**。
//! 代价是上游那一跳不再压缩（真实带宽，不是回环）。
//!
//! # 还有两条**没做**的，写在这里免得被读成「做了」
//!
//! - **不设上游超时**。参考实现用 600 秒；Rust 侧的写法要 `Duration::from_secs`，
//!   而它同样在零定时器护栏的禁用清单里。`Duration::from_millis` 不在禁用清单里，
//!   但护栏还有一条「生产段 `Duration::from_` 的总处数恰好等于登记表条数」——
//!   要用就得往那张表里加一行。⇒ 第一刀不设超时，挂死的上游会占住一个连接线程。
//! - **不碰凭据**。请求头原样转发，**一个都不落进 tee、不落进日志**（`K11` 裁定一：
//!   「不记录 ≠ 不持有」；把 key 接进中转是另一件的硬前置）。

