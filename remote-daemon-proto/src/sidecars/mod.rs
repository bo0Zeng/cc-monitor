//! # 今天这一层里有什么
//!
//! 只有 `codepicture/`，而且**只有协议与判定那一半**（纯函数，一个进程都不起、
//! 一个字节都不落盘）。真正那一跳（HTTP GET · 写盘 · exec）今天**不在盘上**，
//! 为什么不在、要什么才做得了，逐条写在 [`codepicture::fetch`] 的头注里。
//!
//! # 🔴 这一层今天**没有任何生产调用方** —— 这不是忘了接线
