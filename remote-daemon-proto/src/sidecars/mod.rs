//! `K6` 裁定一给的那一层：**我们自己出、我们自己装、我们自己调**的那几个独立进程。
//!
//! 与 `agents/` 对称、语义相反：`agents/` 装的是**用户的** AI CLI（我们只是看它），
//! 这一层装的是**我们随产品分发**的东西。两层的分界线逐字住 `K6` 的那张表，
//! 这里不复述第二份。
//!
//! # 今天这一层里有什么
//!
//! 只有 `codepicture/`，而且两半都在了：**协议与判定**住 [`codepicture::fetch`]（纯函数），
//! **真正那一跳**（HTTP GET · 校验 · 写盘 · 起进程）住 [`codepicture::acquire`]。
//! 三跳各自在**不出网**的前提下被真的走到一次（回环上一台真服务器 · 临时目录 ·
//! 一个临时可执行文件）；**带网那一跳仍然一格都没买到**，理由住 `acquire` 头注第一节。
//!
//! # 🔴 这一层今天**仍然没有任何生产调用方** —— 这不是忘了接线
//!
//! 形状照 `main.rs::unavailable_here` 那条先例（「**能填不真填**」）：接线是一次
//! 有代价的发布决策，不是一次顺手的改动。代价逐条住 [`codepicture::fetch`] 的
//! 「接线那天要同轮做的事」一节。
//!
//! ⚠ 因此整层挂着 `allow(dead_code)`。**它是有期限的**：
//! [`crate::sidecar_fetch_guard`] 里那条「今天恰好 0 个生产调用点」的判据，
//! 红的那一刻就是接线那一刻 —— 同轮把下面这一行摘掉。
//!
//! ## 🔴 09-10 接线那一拍**没有摘掉它**，理由是现打的读数，不是印象
//!
//! 那一拍的写区**不含** `inbound.rs` 与 `main.rs`（`panorama` 那一族命令进 `inbound::REGISTRY`
//! 那一格 PM 自己持有）⇒ **本层今天不可能长出第一个生产调用方**
//! ⇒ 上面那条判据**今天仍然绿**，摘掉这一行的条件**一格都没到**。
//!
//! 而摘掉它的代价现打过：把下面这一行拿掉，`cargo build`（生产构建）从
//! **0 条**警告变成 **45 条** `never used` —— 45 条全是同一个原因（没有调用方），
//! 一条真问题都不是。⇒ 摘了它买到的不是「更早发现死码」，是**把 45 条噪音倒进构建输出**，
//! 而真警告从此藏在里面。
//!
//! ⇒ **这一格如实记成「没做到」，不记成「做了」**：条件是判据变红，不是有人觉得该摘了。
//! ⚠ 与此同时，下面那一行本身被 [`crate::sidecar_fetch_guard`] 钉住了形状 ——
//! 它只许静默**死码**这一种、只许有这**一处**，谁想顺手把它放宽成 `unused` 当场红。
