//! `K-W2D`：代码全景那个 sidecar 的**具名适配层**。
//!
//! `K6` 裁定三给这一层划了四件事（找到那个二进制 · 问它会什么 · 传 argv · 把退出码
//! 翻成语义）。`R2` ① 又给它加了**第零件**：那个二进制**先得到这台机器上来**
//! —— 交付路径是**丙 · 按需拉取**（安装包 +0，daemon 第一次收到全景请求时才去拉）。
//!
//! 本轮只做第零件的**协议与判定**，落在 [`fetch`]。四件事那一半今天一件都没做。
//!
//! # 为什么名字住在这里，不住 `plugin/`
//!
//! `plugin/` 那一层带三条判据钉着「通用层不许认识任何一个具体插件」，而它的采集面
//! 逐字是 `env!("CARGO_MANIFEST_DIR")/src/plugin` ⇒ 具名的东西只能住这一层。
//! ⚠ 但那三条判据的针今天**认不出代码全景这一族词**（它们那张词表自己的头注逐字预言过
//! 这一格）⇒ 「有人把这一族名字写进 `plugin/` 也不会红」这件事**不是本层能治的**，
//! 它归件文件的 `KW2D6`（`plugin/mod.rs` 不在本轮写区）。

