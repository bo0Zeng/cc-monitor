//! **cc-bus 里凡是「拿 id 去点名 tmux」的地方，都要先核身份**。
//!
//! # 这一族出过三处真事故
//!
//! cc-bus 的地址是**名字型**的（`proj_cc:0.0`），而名字会被重用（起会话常按目录基名取名）。
//! 于是「同名会话在」被当成了「它还活着」：敲门文字（带 Enter）**打进陌生占用者的屏幕** ·
//! 收会话时**杀掉无辜进程与会话** · 假报「活」。后两处那两条脚本已经删了；今天 cc-bus 脚本里
//! 一处按名字点名 tmux 的都没有，本表守的是「再长出一处时必须先核身份」。
//!
//! # 今天 cc-bus 不按名字点名 tmux
//!
//! 收件人是会话 id，敲门经 cc-monitor 的公开命令（`session-queue-put` 投进那条会话的输入队，后端投递时照 `@ccm_sid` 认窗格），
//! cc-bus 的脚本里不再起 tmux。真要再长出一处按名字点名的，同一行要问 `#{pane_pid}` 核身份。
//!
//! ⚠ 用**完整地址**而不是 `list-panes -t "=<id>"` —— 后者取的是**当前窗口**的 pane，
//! 用户在自己 agent 的会话里开个新窗口就会假阳性（当年收会话那条脚本第一版栽过，
//! 而**假阳性比不查更坏**：它会让人以为这道保护坏了，进而删掉它）。
//!
//! # 本登记表钉什么
//!
//! 「按变量点名 tmux」的脚本，**要么**同一个文件里做了身份核对（提到 `pane_pid`），
//! **要么**登记在 [`EXEMPT`] 里写明为什么不需要。
//!
//! 「我是哪条会话」不在这张表里：`cc-bus whoami` 只问 cc-monitor 的 `session-self`，不碰 tmux。
