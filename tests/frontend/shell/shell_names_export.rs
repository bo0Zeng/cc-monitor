//! 壳里过语言边界的那几个串（流名 · 事件名 · 数据目录里认的那一行）的生成物：`src/frontend/ui/generated/shell-names.ts`。
//!
//! 值取 Rust 常量本身，界面 import 生成物，不另写一份字面量。`npm run gen:types`（= `cargo test --lib export_bindings`）重写它；
//! 门禁 `generated` 格（`generated-drift.sh`）盖住「改了常量不重跑生成」。

use crate::data_paths::LOGS_DIR_LABEL;
use crate::event_replay::{CHANGED_KIND, PROBE_PROGRESS_KIND, TERMINAL_SCREEN_KIND};
use crate::ui_contract::events::{FRONTEND_READY, LOCAL_BACKEND, UI_ERROR};

/// 生成物的头。`generated-boundary-guard.vitest.ts` 认两样东西：「谁生成的」那一行 ＋「不许手改」那句话。
const HEADER: &str = "\
// 本文件由 `src/frontend/shell/src/event_replay.rs` 的
// `export_bindings_shell_names` 生成（`npm run gen:types`）。Do not edit this file manually.
";

/// `(TS 里的名字, 值, 一句说明)`：名字与 Rust 常量同名。
const NAMES: &[(&str, &str, &str)] = &[
    ("CHANGED_KIND", CHANGED_KIND, "「某样东西变了」那条流（`event_replay.rs::CHANGED_KIND`）；流名是 `changed/<主题>`。"),
    ("PROBE_PROGRESS_KIND", PROBE_PROGRESS_KIND, "测试连接的进度流（`event_replay.rs::PROBE_PROGRESS_KIND`）；后面跟 `/<票>`。"),
    ("TERMINAL_SCREEN_KIND", TERMINAL_SCREEN_KIND, "终端订阅的画面流（`event_replay.rs::TERMINAL_SCREEN_KIND`）；后面跟 `/<票>`。"),
    ("LOGS_DIR_LABEL", LOGS_DIR_LABEL, "数据路径里日志目录那一行的名字（`data_paths.rs::LOGS_DIR_LABEL`）。"),
    ("FRONTEND_READY", FRONTEND_READY, "前端 emit、壳收的就绪事件（`ui_contract::events::FRONTEND_READY`）。"),
    ("LOCAL_BACKEND", LOCAL_BACKEND, "本机后端起没起来变了（`ui_contract::events::LOCAL_BACKEND`）。"),
    ("UI_ERROR", UI_ERROR, "要让用户知道的出错（`ui_contract::events::UI_ERROR`）。"),
];

fn render_shell_names() -> String {
    let mut s = String::from(HEADER);
    for (name, value, doc) in NAMES {
        let lit = serde_json::to_string(value).expect("字符串序列化不会失败");
        s.push_str(&format!("\n/** {doc} */\nexport const {name} = {lit};\n"));
    }
    s
}

/// 生成 `src/frontend/ui/generated/shell-names.ts`。
#[test]
fn export_bindings_shell_names() {
    let out = guard_core::addr::repo_root().join("src/frontend/ui/generated/shell-names.ts");
    std::fs::write(&out, render_shell_names())
        .unwrap_or_else(|e| panic!("写不进 {}：{e}", out.display()));
}
