//! **契约取值集的生成物 ＋ 标识符 · 上游地址那几条判定的金样**。
//!
//! 生成物 `src/frontend/ui/generated/judgment-rules.ts` 装两样：账号种类取值集（J16，`acct_core::AUTH_KINDS`），
//! 界面拿它派生 `AuthKind` 这个类型；机器键里不能当名字的那几个（`cmd_wire::machine::KEYS_NOT_NAMES`），`machineName` 照它挑。账号名（J18）与上游 base URL（J9）界面不判：新建账号表单把原样打的字
//! 交那台后端预演（`accounts-add` 带 `dryRun`），只画它拒的那一句；模型名（J17）同样只在后端写口与起会话时判。
//!
//! 三件事：
//! 1. [`export_bindings_judgment_rules`]：`npm run gen:types`（= `cargo test --lib export_bindings`）重写生成物；
//!    门禁 `generated` 格（`generated-drift.sh`）盖住它 ⇒ 改了取值集不重跑生成就红。
//!    ⚠ 刻意**没有**「盘上那份 == 现算的」那条读回判据：同一趟 `cargo test` 里生成器与它并行跑，读到的可能是写到一半的文件
//!    —— 「生成物不陈旧」只交给门禁那一格的 `git diff`。
//! 2. [`the_shared_golden_agrees_with_the_one_rule`]：金样 `tests/__fixtures__/identifier-rules.golden.json`
//!    的每一条都喂给 Rust 那一份（`session_id_ok` · `model_name_ok` · `account_name_ok`），期望是金样里**手写**的。
//! 3. [`the_upstream_url_golden_agrees_with_the_one_rule`]：金样 `tests/__fixtures__/upstream-url.golden.json` 逐条喂 `upstream_url_core::usable`。
//!    ⚠ 这两份金样今天只有 Rust 一侧在读，住这里是历史位置：它们该住各自的 core crate 自己的判据里。

/// 生成物的头。`generated-boundary-guard.vitest.ts` 认两样东西：「谁生成的」那一行 ＋「不许手改」那句话。
const HEADER: &str = "\
// 本文件由 `src/frontend/shell/src/payload.rs` 的
// `export_bindings_judgment_rules` 生成（`npm run gen:types`）。Do not edit this file manually.
//
// 契约取值集只有一个家（住共享 crate）；界面要拿它派生类型的那几样，数据从那里现生成到这里（不手抄）。
// 账号种类与后端对同一份金样 `tests/__fixtures__/accounts.golden.json`。
";

fn render_judgment_rules() -> String {
    let kinds = serde_json::to_string(&acct_core::AUTH_KINDS).expect("字符串序列化不会失败");
    let mut s = String::from(HEADER);
    // 账号种类的取值集（`AuthKind` 这个类型从它派生，不再手写字面量）。
    s.push_str("\n/** 账号种类的取值集 —— 契约常量住 `acct_core::AUTH_KINDS`。 */\n");
    s.push_str(&format!("export const AUTH_KINDS = {kinds} as const;\n"));
    s.push_str("/** 见 [`AUTH_KINDS`]。 */\n");
    s.push_str("export type AuthKind = (typeof AUTH_KINDS)[number];\n");
    // 机器键里不能当名字给人看的那几个（`machineName` 成品还没到时照它说）。
    let keys =
        serde_json::to_string(&cmd_wire::machine::KEYS_NOT_NAMES).expect("字符串序列化不会失败");
    s.push_str("\n/** 机器键里不能当名字给人看的那几个 —— 契约常量住 `cmd_wire::machine::KEYS_NOT_NAMES`。 */\n");
    s.push_str(&format!(
        "export const KEYS_NOT_NAMES: readonly string[] = {keys};\n"
    ));
    s
}
/// 生成 `src/frontend/ui/generated/judgment-rules.ts`。
#[test]
fn export_bindings_judgment_rules() {
    let repo = guard_core::addr::repo_root();
    let out = repo.join("src/frontend/ui/generated/judgment-rules.ts");
    std::fs::write(&out, render_judgment_rules())
        .unwrap_or_else(|e| panic!("写不进 {}：{e}", out.display()));
}

/// 金样逐条：Rust 那一份（三条）的判定 == 金样里手写的期望（两向：ok 全过、bad 全拒），外加反空真。
#[test]
fn the_shared_golden_agrees_with_the_one_rule() {
    let raw = include_str!("../../__fixtures__/identifier-rules.golden.json");
    let g: serde_json::Value = serde_json::from_str(raw).expect("金样不是合法 JSON");
    let rules: [(&str, fn(&str) -> bool); 3] = [
        ("session_id", shell_quote_core::session_id_ok),
        ("model_name", shell_quote_core::model_name_ok),
        ("account_name", shell_quote_core::account_name_ok),
    ];
    let mut wrong = Vec::new();
    let mut seen = 0usize;
    for (key, ok_fn) in rules {
        for (verdict, want) in [("ok", true), ("bad", false)] {
            let list = g[key][verdict]
                .as_array()
                .unwrap_or_else(|| panic!("金样缺 {key}.{verdict}"));
            assert!(
                !list.is_empty(),
                "金样 {key}.{verdict} 是空的 —— 下面零命中地绿"
            );
            for v in list {
                let s = v.as_str().expect("样本是字符串");
                seen += 1;
                if ok_fn(s) != want {
                    wrong.push(format!("{key}：{s:?} 期望 {verdict}"));
                }
            }
        }
    }
    assert!(seen > 30, "金样只有 {seen} 条 —— 读坏了");
    assert_eq!(wrong, Vec::<String>::new(), "Rust 那一份与共用金样对不上");
}

/// 金样 `tests/__fixtures__/upstream-url.golden.json` 逐条：`upstream_url_core::usable` 的结论 == 手写的 want。
#[test]
fn the_upstream_url_golden_agrees_with_the_one_rule() {
    let raw = include_str!("../../__fixtures__/upstream-url.golden.json");
    let g: serde_json::Value = serde_json::from_str(raw).expect("金样不是合法 JSON");
    let cases = g["cases"].as_array().expect("金样缺 cases");
    assert!(cases.len() > 40, "金样只有 {} 条 —— 读坏了", cases.len());
    let mut wrong = Vec::new();
    for c in cases {
        let url = c["url"].as_str().expect("url 是字符串");
        let got = upstream_url_core::usable(url)
            .err()
            .map(upstream_url_core::Unusable::code);
        if got != c["want"].as_str() {
            wrong.push(format!("{url:?}：得 {got:?}，金样 {:?}", c["want"]));
        }
    }
    assert_eq!(wrong, Vec::<String>::new(), "Rust 那一份与共用金样对不上");
}

/// ★★★ E4 ＋ E9：**monitor 生产树里零上游选择、零路由语法、零门牌字面量**。
///
/// 守的要求：必须拆 1（`APIKEY_TABLE_AGENT` · `AGENTS_WITH_DEFAULT_UPSTREAM` · 路由前缀 · 段闸 · 端口两边各一份）·
/// 「业务解释只有一个家」· 目标「端口 · 路由渲染 · 段的字符闸收进共享 crate，一份实现两侧 use」。
///
/// 人群：`src/frontend/shell/src/**/*.rs` 生产段（剥注释与测试段）× 下面两张表，**零命中**；
/// 正控（异源，证明尺子不瞎）：同一把尺子在后端上游选择 / 共享 crate 的生产段上**各数得到**每一样（逐名点住址）。
/// 端口与钥匙路径那两样还要求后端生产段零字面量（它们只许 `use` 共享 crate）。
#[test]
fn us1_the_monitor_holds_no_upstream_selection_and_no_route_grammar() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    // 住址按仓根写（`src/…`），搬树时跟着仓根走，不跟着本 crate 的深度走。
    let repo = guard_core::addr::repo_root();
    let read =
        |rel: &str| guard_core::production_code(&std::fs::read_to_string(repo.join(rel)).unwrap());
    // (名字, 它今天的家)
    let words: [(&str, &str); 8] = [
        (
            "APIKEY_TABLE_AGENT",
            "src/backend/accounts/upstream_select/mod.rs::CREDENTIALS_FILE_AGENT",
        ),
        (
            "AGENTS_WITH_DEFAULT_UPSTREAM",
            "src/backend/agents/mod.rs::default_upstreams",
        ),
        (
            "apikey_endpoint_for",
            "src/backend/accounts/upstream_select/endpoint.rs::decide_launch",
        ),
        (
            "relay_endpoint_for",
            "src/backend/accounts/upstream_select/endpoint.rs::decide_launch",
        ),
        (
            "RelayAsk",
            "src/backend/accounts/upstream_select/endpoint.rs::decide_launch",
        ),
        (
            "apikey_rows",
            "src/backend/accounts/upstream_select/file_face.rs::rows_at",
        ),
        (
            "read_accounts",
            "src/backend/accounts/upstream_select/file_face.rs::key_facts_at",
        ),
        (
            "apikey_routed_subset",
            "src/backend/observe/accounts_query.rs::list_product_with",
        ),
    ];
    let literals: [(&str, &str); 4] = [
        ("\"/s/\"", "src/common/relay-route-core/src/lib.rs"),
        ("\"/t/\"", "src/common/relay-route-core/src/lib.rs"),
        ("8788", "src/common/relay-route-core/src/lib.rs"),
        (
            "\".cc-monitor/relay-key\"",
            "src/common/relay-route-core/src/lib.rs",
        ),
    ];
    let mut hits = Vec::new();
    for (at, src) in guard_core::scan_tree_excluding(&root.join("src"), &["rs"], &[]) {
        let prod = guard_core::production_code(&src);
        for (w, _) in words {
            if guard_core::contains_word(&prod, w) {
                hits.push(format!("{} · `{w}`", at.display()));
            }
        }
        for (l, _) in literals {
            if prod.contains(l) {
                hits.push(format!("{} · {l}", at.display()));
            }
        }
    }
    assert!(
        hits.is_empty(),
        "monitor 生产树里又长出了上游选择 / 路由语法 / 门牌字面量：\n  {}",
        hits.join("\n  ")
    );
    // 正控：家里数得到（名字那一张：家文件里那个「今天的名字」在；字面量那一张：共享 crate 里在）。
    for (w, home) in words {
        let (file, sym) = home.split_once("::").unwrap();
        assert!(
            guard_core::contains_word(&read(file), sym),
            "`{w}` 的家 {home} 里数不到 `{sym}` —— 尺子或住址坏了"
        );
    }
    for (l, home) in literals {
        assert!(
            read(home).contains(l),
            "共享 crate 里数不到 {l} —— 尺子是瞎的"
        );
    }
    // 后端那一半：端口与钥匙路径只许 `use` 共享 crate（零字面量）。
    let mut backend_hits = Vec::new();
    for (at, src) in guard_core::scan_tree_excluding(&repo.join("src/backend"), &["rs"], &[]) {
        let prod = guard_core::production_code(&src);
        for l in ["8788", "\".cc-monitor/relay-key\""] {
            if prod.contains(l) {
                backend_hits.push(format!("{} · {l}", at.display()));
            }
        }
    }
    assert!(
        backend_hits.is_empty(),
        "后端生产树里还有门牌字面量（该 use relay_route_core）：{backend_hits:?}"
    );
}
