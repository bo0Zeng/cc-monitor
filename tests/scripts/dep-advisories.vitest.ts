// @vitest-environment node
/**
 * 依赖漏洞判据（`tests/scripts/dep-advisories.mjs`）的离线单测：不连真 OSV。
 * 锁与公告都是测试里现拼的最小样子（包名 `demo-*`），照 Cargo.lock · package-lock.json v3 · OSV 公告的字段形状。
 * 端到端那几条起一台只听 127.0.0.1 的假 OSV，经 `OSV_API` 指给脚本。
 */
import { spawn, spawnSync } from "node:child_process";
import { createServer, type IncomingMessage, type ServerResponse } from "node:http";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import type { AddressInfo } from "node:net";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { REPO_ROOT } from "../test-support/repo-root.ts";
import {
  classify,
  cmpVersion,
  fixedVersion,
  parseCargoLock,
  parsePackageLock,
  parseWaivers,
  // @ts-expect-error 纯 JS 脚本，没有类型声明
} from "./dep-advisories.mjs";

const SCRIPT = resolve(REPO_ROOT, "tests/scripts/dep-advisories.mjs");

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "demo-app"
version = "0.1.0"
dependencies = [
 "demo-tls",
]

[[package]]
name = "demo-tls"
version = "1.2.3"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "demo-git"
version = "0.4.0"
source = "git+https://example.invalid/demo-git#abc"

[[package]]
name = "demo-sparse"
version = "2.0.0-rc.1"
source = "sparse+https://index.crates.io/"
`;

const PACKAGE_LOCK = JSON.stringify({
  name: "demo",
  lockfileVersion: 3,
  packages: {
    "": { name: "demo", version: "1.0.0" },
    "node_modules/demo-ui": { version: "3.0.0" },
    "node_modules/@demo/scoped": { version: "1.1.0", dev: true },
    "node_modules/demo-ui/node_modules/demo-inner": { version: "0.2.0" },
    "packages/local": { version: "0.0.1" },
    "node_modules/local": { resolved: "packages/local", link: true },
  },
});

/** OSV 公告的样子：`informational`（RustSec 的 unmaintained · unsound）住在 affected 那一项的 database_specific 里。 */
function vuln(id: string, name: string, events: object[], extra: object = {}, informational: string | null = null) {
  return {
    id,
    summary: `${id} summary`,
    affected: [
      {
        package: { name, ecosystem: "crates.io" },
        ranges: [{ type: "SEMVER", events }],
        database_specific: { informational },
      },
    ],
    ...extra,
  };
}

describe("解析锁", () => {
  it("Cargo.lock 只收 registry 来的包（registry+ · sparse+），path 与 git 的不问", () => {
    expect(parseCargoLock(CARGO_LOCK)).toEqual([
      { name: "demo-tls", version: "1.2.3" },
      { name: "demo-sparse", version: "2.0.0-rc.1" },
    ]);
  });
  it("package-lock 取 node_modules 下的包名（连 scoped 与嵌套的）、记 dev，根与 link 不问", () => {
    expect(parsePackageLock(PACKAGE_LOCK)).toEqual([
      { name: "demo-ui", version: "3.0.0", dev: false },
      { name: "@demo/scoped", version: "1.1.0", dev: true },
      { name: "demo-inner", version: "0.2.0", dev: false },
    ]);
  });
  it("豁免表一行一条：包 编号 理由；注释与空行跳过，没写理由就拒", () => {
    expect(parseWaivers("# 注释\n\ndemo-zip  RUSTSEC-0000-0001  只自己解条目、不调 extract\n")).toEqual([
      { pkg: "demo-zip", id: "RUSTSEC-0000-0001", why: "只自己解条目、不调 extract", line: 3 },
    ]);
    expect(() => parseWaivers("demo-zip RUSTSEC-0000-0001\n")).toThrow(/理由/);
  });
});

describe("版本与修复版", () => {
  it("版本比较照 semver：数字段按数、预发布排在正式版前", () => {
    expect(cmpVersion("0.23.43", "0.23.46")).toBeLessThan(0);
    expect(cmpVersion("1.10.0", "1.9.9")).toBeGreaterThan(0);
    expect(cmpVersion("0.10.0-rc.18", "0.10.0")).toBeLessThan(0);
    expect(cmpVersion("0.10.0-rc.9", "0.10.0-rc.18")).toBeLessThan(0);
    expect(cmpVersion("2.4.2", "2.4.2")).toBe(0);
  });
  it("修复版取罩住本版那一段的 fixed；那一段没收口（last_affected / 没写）⇒ 没有修复版", () => {
    const v = vuln("X-1", "demo-tls", [{ introduced: "0" }, { fixed: "1.0.5" }, { introduced: "1.2.0" }, { fixed: "1.2.9" }]);
    expect(fixedVersion(v, "crates.io", "demo-tls", "1.2.3")).toBe("1.2.9");
    expect(fixedVersion(v, "crates.io", "demo-tls", "1.0.1")).toBe("1.0.5");
    const open = vuln("X-2", "demo-tls", [{ introduced: "0" }]);
    expect(fixedVersion(open, "crates.io", "demo-tls", "1.2.3")).toBeNull();
    const last = vuln("X-3", "demo-tls", [{ introduced: "0" }, { last_affected: "1.2.3" }]);
    expect(fixedVersion(last, "crates.io", "demo-tls", "1.2.3")).toBeNull();
    expect(fixedVersion(v, "npm", "demo-tls", "1.2.3")).toBeNull();
  });
});

describe("判定", () => {
  const base = { ecosystem: "crates.io", name: "demo-tls", version: "1.2.3", shipped: true, waivers: [] };
  const fixed = vuln("RUSTSEC-0000-0002", "demo-tls", [{ introduced: "0" }, { fixed: "1.2.4" }], {
    aliases: ["GHSA-demo-0002"],
  });
  it("随产品发的包有修复版 ⇒ 红", () => {
    expect(classify({ ...base, vuln: fixed })).toMatchObject({ level: "red", fixed: "1.2.4" });
  });
  it("豁免表里登了（编号或它的别名都认）⇒ 豁免，不红", () => {
    const w = [{ pkg: "demo-tls", id: "GHSA-demo-0002", why: "碰不到", line: 1 }];
    expect(classify({ ...base, vuln: fixed, waivers: w })).toMatchObject({ level: "waived" });
    const other = [{ pkg: "demo-other", id: "GHSA-demo-0002", why: "碰不到", line: 1 }];
    expect(classify({ ...base, vuln: fixed, waivers: other }).level).toBe("red");
  });
  it("开发依赖 · 无修复版 · 不再维护 ⇒ 只印", () => {
    expect(classify({ ...base, shipped: false, vuln: fixed }).level).toBe("info");
    const open = vuln("RUSTSEC-0000-0003", "demo-tls", [{ introduced: "0" }]);
    expect(classify({ ...base, vuln: open }).level).toBe("info");
    const unmaint = vuln("RUSTSEC-0000-0004", "demo-tls", [{ introduced: "0" }, { fixed: "9.0.0" }], {}, "unmaintained");
    expect(classify({ ...base, vuln: unmaint }).level).toBe("info");
  });
  it("unsound 照漏洞算：有修复版就红", () => {
    const unsound = vuln("RUSTSEC-0000-0005", "demo-tls", [{ introduced: "0" }, { fixed: "1.3.0" }], {}, "unsound");
    expect(classify({ ...base, vuln: unsound }).level).toBe("red");
  });
  it("撤回了的公告不算", () => {
    expect(classify({ ...base, vuln: { ...fixed, withdrawn: "2026-01-01T00:00:00Z" } }).level).toBe("skip");
  });
});

// ── 端到端：假 OSV ──────────────────────────────────────────────────────────────
type Handler = (req: IncomingMessage, body: string, res: ServerResponse) => void;
const cleanups: (() => void)[] = [];
afterEach(() => {
  for (const f of cleanups.splice(0)) f();
});

function fixtureRoot(waivers = ""): string {
  const root = mkdtempSync(join(tmpdir(), "dep-advisories-"));
  cleanups.push(() => rmSync(root, { recursive: true, force: true }));
  const put = (rel: string, text: string) => {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), text);
  };
  put("src/backend/Cargo.lock", CARGO_LOCK);
  put("src/frontend/shell/Cargo.lock", CARGO_LOCK);
  put("package-lock.json", PACKAGE_LOCK);
  put("tests/scripts/dep-advisories-waived.txt", waivers);
  return root;
}

async function fakeOsv(handler: Handler): Promise<string> {
  const server = createServer((req, res) => {
    let body = "";
    req.on("data", (c) => (body += c));
    req.on("end", () => handler(req, body, res));
  });
  await new Promise<void>((ok) => server.listen(0, "127.0.0.1", ok));
  cleanups.push(() => server.close());
  return `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
}

/** 只给 demo-tls 一条公告（有修复版），别的包都干净。 */
const oneHit: Handler = (req, body, res) => {
  res.setHeader("content-type", "application/json");
  if (req.url === "/v1/querybatch") {
    const { queries } = JSON.parse(body) as { queries: { package: { name: string } }[] };
    const results = queries.map((q) =>
      q.package.name === "demo-tls" ? { vulns: [{ id: "RUSTSEC-0000-0002" }, { id: "GHSA-demo-0002" }] } : {},
    );
    res.end(JSON.stringify({ results }));
    return;
  }
  const id = req.url?.replace("/v1/vulns/", "") ?? "";
  const aliases = id.startsWith("GHSA") ? ["RUSTSEC-0000-0002"] : ["GHSA-demo-0002"];
  res.end(JSON.stringify(vuln(id, "demo-tls", [{ introduced: "0" }, { fixed: "1.2.4" }], { aliases })));
};

function runScript(root: string, api: string, ...extra: string[]): Promise<{ code: number | null; out: string }> {
  return new Promise((ok) => {
    const child = spawn(process.execPath, [SCRIPT, "--root", root, ...extra], {
      env: { ...process.env, OSV_API: api },
    });
    let out = "";
    child.stdout.on("data", (c) => (out += c));
    child.stderr.on("data", (c) => (out += c));
    child.on("close", (code) => ok({ code, out }));
  });
}

describe("端到端（假 OSV）", () => {
  it("有修复版的命中 ⇒ 退 1、印红；GHSA 与 RUSTSEC 互为别名只算一条", async () => {
    const r = await runScript(fixtureRoot(), await fakeOsv(oneHit));
    expect(r.code, r.out).toBe(1);
    expect(r.out).toMatch(/demo-tls 1\.2\.3 .*RUSTSEC-0000-0002.*1\.2\.4/);
    expect(r.out).toMatch(/DEP-ADVISORIES: 红 2 条/); // 两份 Cargo.lock 各一条
  });
  it("登了豁免 ⇒ 退 0", async () => {
    const r = await runScript(fixtureRoot("demo-tls RUSTSEC-0000-0002 夹具：碰不到\n"), await fakeOsv(oneHit));
    expect(r.code, r.out).toBe(0);
    expect(r.out).toMatch(/DEP-ADVISORIES: OK/);
  });
  it("豁免表里一行没命中任何公告（死行）⇒ 红，叫删掉", async () => {
    const r = await runScript(
      fixtureRoot("demo-tls RUSTSEC-0000-0002 夹具：碰不到\ndemo-ui GHSA-gone-0001 早修了\n"),
      await fakeOsv(oneHit),
    );
    expect(r.code, r.out).toBe(1);
    expect(r.out).toMatch(/GHSA-gone-0001/);
  });
  it("--rev 判的是那个提交里的锁与豁免表，不是工作树里的", async () => {
    const root = fixtureRoot("demo-tls RUSTSEC-0000-0002 夹具：碰不到\n");
    const git = (...a: string[]) =>
      spawnSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", ...a], { cwd: root });
    git("init", "-q");
    git("add", "-A");
    git("commit", "-q", "-m", "fixture");
    writeFileSync(join(root, "tests/scripts/dep-advisories-waived.txt"), ""); // 工作树里删掉豁免：不该被读到
    const api = await fakeOsv(oneHit);
    expect((await runScript(root, api, "--rev", "HEAD")).code).toBe(0);
    expect((await runScript(root, api)).code).toBe(1);
    const missing = await runScript(root, api, "--rev", "no-such-rev");
    expect(missing.code, missing.out).toBe(2);
  });
  it("一份锁里一个 registry 包都没读出来（锁的写法变了 · 读错了文件）⇒ 判不了，不当没漏洞", async () => {
    const root = fixtureRoot();
    writeFileSync(join(root, "src/frontend/shell/Cargo.lock"), "version = 4\n");
    const r = await runScript(root, await fakeOsv(oneHit));
    expect(r.code, r.out).toBe(2);
    expect(r.out).toMatch(/src\/frontend\/shell\/Cargo\.lock/);
  });
  it("OSV 回 500 ⇒ 判不了（退 2），不当通过", async () => {
    const api = await fakeOsv((_q, _b, res) => {
      res.statusCode = 500;
      res.end("oops");
    });
    const r = await runScript(fixtureRoot(), api);
    expect(r.code, r.out).toBe(2);
    expect(r.out).toMatch(/DEP-ADVISORIES: 判不了/);
  });
  it("OSV 回的条数对不上 ⇒ 判不了", async () => {
    const api = await fakeOsv((_q, _b, res) => res.end(JSON.stringify({ results: [] })));
    const r = await runScript(fixtureRoot(), api);
    expect(r.code, r.out).toBe(2);
  });
  it("连不上 OSV ⇒ 判不了", async () => {
    const api = await fakeOsv(oneHit);
    const dead = api; // 先拿到端口再关掉，这个端口上就没人听了
    cleanups.splice(0).forEach((f) => f());
    const r = await runScript(fixtureRoot(), dead);
    expect(r.code, r.out).toBe(2);
  });
});
