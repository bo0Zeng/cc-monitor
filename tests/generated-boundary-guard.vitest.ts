    // 两种诚实形态，取决于 serde 怎么处置 None：
    // - 有 `skip_serializing_if` ⇒ 线上**省略** ⇒ `ts(optional, type = "number")` ⇒ `x?: number`
    // - 无 `skip_serializing_if` ⇒ 线上是 **null** ⇒ `ts(type = "number | null")` ⇒ `x: number | null`
